import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

import type { Registry } from '@polymorph/registry'

/**
 * The plain-text files an agent fetches first, in the `llms.txt` convention
 * (https://llmstxt.org).
 *
 * `/llms.txt` is short. It says what the system is, links the contract, gives
 * the commands that connect an agent to it, and lists the rules from the
 * registry. `/llms-full.txt` is the contract itself: the system card, then the
 * rules page. `vite.config.ts` serves both, and the card as `/system-card.md`,
 * from the files the registry generator writes (`readLlmsFiles`). Those files
 * are regenerated by every build (`prebuild`), every dev start (`predev`) and
 * every `pnpm registry`. The dev server reads them per request, so in dev they
 * are as current as the last of those runs, and fall behind a source change
 * until the next one. The build writes them into `dist/` from a fresh run.
 */

/** Where the site serves each file. */
export const LLMS_PATHS = {
  index: '/llms.txt',
  full: '/llms-full.txt',
  card: '/system-card.md',
} as const

/** The repository an agent clones for the CLI and the MCP server, which are not published. */
export const REPOSITORY = 'https://github.com/metamorph-labs/polymorph'

/** The bins an agent runs, relative to a checkout. `llms.test.ts` checks that they exist. */
export const MCP_BIN = 'packages/mcp/bin/polymorph-mcp.js'
export const CLI_BIN = 'packages/cli/bin/polymorph.js'

export function llmsTxt(registry: Registry): string {
  const rules = registry.laws.filter((law) => law.applies === 'application')
  return [
    '# Polymorph',
    '',
    `> A design system: a closed vocabulary of ${registry.components.length} components ` +
      'and a theme engine, rendered in React, Vue, Svelte, Solid and Angular on the web, as ' +
      'custom elements (`<poly-button>`) on a page written in HTML, and in SwiftUI and Compose on ' +
      'iOS and Android. Application code composes the components and binds content. The theme ' +
      'makes every style decision.',
    '',
    '- The vocabulary is closed. Application code renders the members the system card lists. It ' +
      'adds no stylesheet, style value, raw interactive element, icon import or motion of its own.',
    '- Screens are specs or TSX under the rules. A spec is JSON that `validate` checks and ' +
      '`emit_screen` compiles for the app’s framework, or to SwiftUI or Compose for a spec whose ' +
      'platform is `ios` or `android`. Hand-written code composes the same members under the ' +
      'same red rules.',
    '- Every violation names its fix. A red rule says what to write instead, and `validate` adds ' +
      'the exception-ladder rungs that answer it.',
    '',
    '## The contract',
    '',
    `- [System card](${LLMS_PATHS.card}): every member, its props, the token families and the ` +
      'rules, in one read. Read it before writing code.',
    `- [Full text](${LLMS_PATHS.full}): the system card, then the rules page with the exception ` +
      'ladder.',
    '',
    '## Commands',
    '',
    `The MCP server and the CLI run from a checkout of ${REPOSITORY}.`,
    '',
    `- MCP server, over stdio: \`node <checkout>/${MCP_BIN}\`, started in the project it ` +
      'writes into. Call `get_system_card` first.',
    `- A new app: \`node <checkout>/${CLI_BIN} init my-app\`. It writes a Vite app that ` +
      'installs the packages, with a theme, the red rules, the MCP configuration and a first ' +
      'screen spec; `--framework vue`, `svelte`, `solid` or `angular` writes it in that framework. ' +
      '`--framework elements` writes a page with no build instead: the files it loads the ' +
      'elements from, a theme sheet and an example page.',
    '',
    '## Rules on application code',
    '',
    ...rules.map((law) => `- \`${law.name}\`: ${law.summary}`),
    '',
    '## The exception ladder',
    '',
    'A violation that is intended climbs to the lowest rung that covers it.',
    '',
    ...registry.exceptions.ladder.map(
      (rung) => `${rung.rung}. ${rung.name}: ${rung.summary.replace(/\.?$/, '.')}`,
    ),
    '',
  ].join('\n')
}

/** The system card, then the rules page, as one document. */
export function llmsFullTxt(card: string, rules: string): string {
  return `${card.trimEnd()}\n\n${rules.trimEnd()}\n`
}

/** One file the site serves: its media type and its text. */
export interface LlmsFile {
  type: 'text/plain' | 'text/markdown'
  body: string
}

/**
 * Every file in `LLMS_PATHS`, keyed by path, built from the registry the
 * generator wrote under `root` (the repository) and from `docs/rules.md`.
 */
export function readLlmsFiles(root: string): Record<string, LlmsFile> {
  const read = (path: string) => readFileSync(resolve(root, path), 'utf8')
  const card = read('registry/system-card.md')
  const registry = JSON.parse(read('registry/registry.json')) as Registry
  return {
    [LLMS_PATHS.index]: { type: 'text/plain', body: llmsTxt(registry) },
    [LLMS_PATHS.full]: { type: 'text/plain', body: llmsFullTxt(card, read('docs/rules.md')) },
    [LLMS_PATHS.card]: { type: 'text/markdown', body: card },
  }
}
