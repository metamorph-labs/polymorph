import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

import type { Registry } from '@polymorph/registry'

import { GUIDE_GROUPS, GUIDES, guideMarkdownPath, guidesInGroup } from './guide-catalogue'
import { rewriteLinks, stripComments } from './guide-links'
import { TOOLS_NAME } from './reference/facts'

/**
 * The plain-text files an agent fetches first, in the `llms.txt` convention
 * (https://llmstxt.org).
 *
 * `/llms.txt` is short. It says what the system is, links the contract, gives
 * the commands that connect an agent to it, lists the guides, and lists the
 * rules from the registry. `/llms-full.txt` is the contract itself: the system
 * card, then the rules page. Each guide is also served as its markdown, at
 * `/guides/<slug>.md`, because a reader that is a model takes a document's
 * text and has no use for the page drawn around it. `vite.config.ts` serves
 * all of them, and the card as `/system-card.md`, from the files the registry
 * generator writes and from `docs/` (`readLlmsFiles`). The generator's files
 * are regenerated by every build (`prebuild`), every dev start (`predev`) and
 * every `pnpm registry`. The dev server reads them per request, so in dev they
 * are as current as the last of those runs, and fall behind a source change
 * until the next one. The build writes them into `dist/` from a fresh run.
 */

/** Where the site serves each file. */
export const LLMS_PATHS = {
  index: '/llms.txt',
  full: '/llms-full.txt',
  card: '/system-card.md',
} as const

/** The repository a guide's link to a source file points into. */
export const REPOSITORY = 'https://github.com/metamorph-labs/polymorph'

/**
 * The command an agent runs the CLI and the MCP server with: the published tools at the
 * registry's release range, by their scoped name, with `npx`. The unscoped `polymorph` on npm is
 * another package.
 */
export const toolsCommand = (registry: Registry): string =>
  `npx -y ${TOOLS_NAME}@^${registry.version}`

/**
 * `/llms.txt`. `origin` is the site's address with no trailing slash, or the
 * empty string when the build does not know it. A link is then written from
 * the site's root, which a reader resolves against the file's own address.
 */
export function llmsTxt(registry: Registry, origin = ''): string {
  const rules = registry.laws.filter((law) => law.applies === 'application')
  return [
    '# Polymorph',
    '',
    `> A design system: a closed vocabulary of ${registry.components.length} components ` +
      'and a theme engine, rendered in React, Vue, Svelte, Solid and Angular on the web, as ' +
      'custom elements (`<poly-button>`) on a page written in HTML, and in SwiftUI and Compose on ' +
      'iOS and Android. Application code composes the components and binds content. The theme ' +
      'makes every style decision.',
    '',
    '- The vocabulary is closed. Application code renders the members the system card lists. It ' +
      'adds no stylesheet, style value, raw interactive element, icon import or motion of its own.',
    '- Screens are specs or TSX under the rules. A spec is JSON that `validate` checks and ' +
      '`emit_screen` compiles for the app’s framework, or to SwiftUI or Compose for a spec whose ' +
      'platform is `ios` or `android`. Hand-written code composes the same members under the ' +
      'same red rules.',
    '- Every violation names its fix. A red rule says what to write instead, and `validate` adds ' +
      'the exception-ladder rungs that answer it.',
    '',
    '## The contract',
    '',
    `- [System card](${origin}${LLMS_PATHS.card}): every member, its props, the token families and the ` +
      'rules, in one read. Read it before writing code.',
    `- [Full text](${origin}${LLMS_PATHS.full}): the system card, then the rules page with the exception ` +
      'ladder.',
    '',
    '## Commands',
    '',
    `The MCP server and the CLI are one published package, \`${TOOLS_NAME}\`. Run it with ` +
      '`npx` by that scoped name; it needs no checkout.',
    '',
    `- MCP server, over stdio: \`${toolsCommand(registry)} mcp\`, started in the project it ` +
      'writes into. Call `get_system_card` first.',
    `- A new app: \`${toolsCommand(registry)} init my-app\`. It writes a Vite app that ` +
      'installs the packages, with a theme, the red rules, the MCP configuration and a first ' +
      'screen spec; `--framework vue`, `svelte`, `solid` or `angular` writes it in that framework. ' +
      '`--framework elements` writes a page with no build instead: the files it loads the ' +
      'elements from, a theme sheet and an example page.',
    '- Every MCP tool is also a verb of the same command, for a harness with a shell and no MCP ' +
      'client: `card`, `validate`, `emit`, `render` and the rest. `--help` lists them, and ' +
      '`--json` prints the tool’s answer.',
    `- A coding agent's files in an app that exists: \`${toolsCommand(registry)} agents\`. It ` +
      'writes a block in `AGENTS.md`, the skills (`polymorph-screen`, `polymorph-rules`, ' +
      '`polymorph-setup`, `polymorph-theme`) and the MCP server for Claude Code, Codex and Cursor. ' +
      `Claude Code and Codex can install the same skills and server as a plugin from the ` +
      `repository's marketplace instead: \`claude plugin marketplace add metamorph-labs/polymorph\`.`,
    '',
    '## Guides',
    '',
    'Each guide is a markdown file. A guide links the other guides by their files.',
    ...GUIDE_GROUPS.flatMap((group) => [
      '',
      `### ${group.title}`,
      '',
      ...guidesInGroup(group.id).map(
        (guide) =>
          `- [${guide.title}](${origin}${guideMarkdownPath(guide.slug)}): ${guide.description}`,
      ),
    ]),
    '',
    '## Rules on application code',
    '',
    ...rules.map((law) => `- \`${law.name}\`: ${law.summary}`),
    '',
    '## The exception ladder',
    '',
    'A violation that is intended climbs to the lowest rung that covers it.',
    '',
    ...registry.exceptions.ladder.map(
      (rung) => `${rung.rung}. ${rung.name}: ${rung.summary.replace(/\.?$/, '.')}`,
    ),
    '',
  ].join('\n')
}

/**
 * A guide as the site serves it at `/guides/<slug>.md`: the file in `docs/`
 * with its links rewritten, because the file's own links are relative to the
 * repository. A link to another guide goes to that guide's markdown file, and
 * a link to any other file in the repository goes to it on GitHub. A member's
 * spec is one of those: the spec is markdown too, and it says more than the
 * member's page does. A comment to the file's editors is left out, as on the
 * guide's page.
 */
export function guideMarkdown(slug: string, source: string, origin = ''): string {
  return rewriteLinks(stripComments(source), {
    guide: slug,
    guides: GUIDE_SLUGS,
    memberForSpec: () => undefined,
    repository: REPOSITORY,
    guideHref: (other) => `${origin}${guideMarkdownPath(other)}`,
  })
}

const GUIDE_SLUGS: ReadonlySet<string> = new Set(GUIDES.map((guide) => guide.slug))

/** Every path `readLlmsFiles` holds a file for, which needs no file read to know. */
export function llmsPaths(): ReadonlySet<string> {
  return new Set([
    ...Object.values<string>(LLMS_PATHS),
    ...GUIDES.map((guide) => guideMarkdownPath(guide.slug)),
  ])
}

/**
 * The system card, then the rules guide, as one document. The rules are the
 * text `/guides/rules.md` serves, so their links resolve from this file too.
 */
export function llmsFullTxt(card: string, rules: string): string {
  return `${card.trimEnd()}\n\n${rules.trimEnd()}\n`
}

/** One file the site serves: its media type and its text. */
export interface LlmsFile {
  type: 'text/plain' | 'text/markdown'
  body: string
}

/**
 * Every file in `LLMS_PATHS` and each guide's markdown file, keyed by path,
 * built from the registry the generator wrote under `root` (the repository)
 * and from `docs/`. `origin` is the site's address, as `llmsTxt` takes it.
 */
export function readLlmsFiles(root: string, origin = ''): Record<string, LlmsFile> {
  const read = (path: string) => readFileSync(resolve(root, path), 'utf8')
  const card = read('registry/system-card.md')
  const registry = JSON.parse(read('registry/registry.json')) as Registry
  return {
    [LLMS_PATHS.index]: { type: 'text/plain', body: llmsTxt(registry, origin) },
    [LLMS_PATHS.full]: {
      type: 'text/plain',
      body: llmsFullTxt(card, guideMarkdown('rules', read('docs/rules.md'), origin)),
    },
    [LLMS_PATHS.card]: { type: 'text/markdown', body: card },
    ...Object.fromEntries(
      GUIDES.map((guide): [string, LlmsFile] => [
        guideMarkdownPath(guide.slug),
        {
          type: 'text/markdown',
          body: guideMarkdown(guide.slug, read(`docs/${guide.slug}.md`), origin),
        },
      ]),
    ),
  }
}
