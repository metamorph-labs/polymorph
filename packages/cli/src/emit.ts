/**
 * The token list passed to the ghost-token rule, as a wrapped literal.
 *
 * It is written into the config instead of imported, because at lint time
 * there is nothing to import it from. The vendored theme data is a system and
 * a palette (values, not property names). The module that turns them into a
 * sheet is TypeScript, and node loads a Stylelint config natively. So the
 * install records what it does know at install time: the registry's list of
 * every `--pm-*` the emitter writes.
 *
 * Staleness is limited by the same mechanism as every generated file: `add`
 * and `update` rewrite this file, and the manifest records it as generated so
 * `diff` never reports it. A list one version behind reports a token added
 * upstream as a ghost. The fix is `polymorph update`, and the generated file's
 * comment says so.
 */
function tokenList(tokens: string[], indent: string): string {
  const lines: string[] = []
  let line = ''

  for (const token of [...tokens].sort()) {
    const next = `'${token}',`
    if (line !== '' && `${indent}${line} ${next}`.length > 96) {
      lines.push(indent + line)
      line = next
    } else line = line === '' ? next : `${line} ${next}`
  }
  if (line !== '') lines.push(indent + line)

  return lines.join('\n')
}

/**
 * The Stylelint half.
 *
 * Override order is the mechanism. The application half is turned on for
 * every stylesheet and then turned *off* for the vendored tree, because a
 * later override wins. The vendored tree is the vocabulary and its compiled
 * theme now: a component declares transitions, and the theme sheet declares
 * every `--pm-*` token under `[data-system]` and `[data-palette]` selectors and
 * writes the system's `[data-member]` exceptions. Application CSS still may
 * not do any of it. These are the motion containment law and the rules that
 * keep application CSS from re-making the theme's decisions, carried with the
 * install.
 *
 * It is written as two overrides on purpose, not as one negated glob. A `'!…'`
 * in the first pattern list would depend on how Stylelint's matcher handles
 * negation. Two overrides depend only on "the last one wins", which is
 * documented, and the scratch app checks both halves.
 *
 * The ghost-token rule is the only law here that governs *both* halves. It is
 * declared once, in the first override, because Stylelint merges an override's
 * rules over the rules already in force instead of replacing them. Both halves
 * need it, for different reasons. The vendored tree is recipes that read
 * tokens. Any other stylesheet in the consumer's repository that reads a
 * `--pm-*` token reads one the install owns. Misremembered names occur there,
 * and the dropped declaration looks like a broken component. (A `<Bespoke>`
 * zone is not a stylesheet. It styles itself through `style` props, and
 * `no-app-css` has no zone exemption.)
 *
 * `token-values-only` takes the installed theme's `values`, as the ESLint
 * half's rules do, so a raw value in a vendored recipe is reported with the
 * token it should read.
 */
export function stylelintFragment(
  dir: string,
  tokens: string[] = [],
  values: TokenValues = {},
): string {
  return `${BANNER('the red rules, travelling with the install', 'put your own rules in your config, not here')}
import polymorph, { RULE_NAMES } from '@polymorph/rules/stylelint'

/**
 * Every custom property your installed themes emit — what \`no-ghost-tokens\`
 * checks a \`var(--pm-…)\` against, alongside the properties each stylesheet
 * declares for itself.
 *
 * Regenerated by \`polymorph add\` and \`polymorph update\`. If a token you know
 * exists is reported as a ghost, this list is older than your vocabulary: run
 * \`polymorph update\`.
 */
const TOKENS = [
${tokenList(tokens, '  ')}
]

${VALUES_DOC}
const VALUES = ${valuesLiteral(values)}

/** @type {import('stylelint').Config} */
export default {
  plugins: [...polymorph],
  // Stylelint refuses a config with no top-level \`rules\` at all, even when every
  // rule it will apply lives in an override. Yours go here.
  rules: {},
  overrides: [
    {
      // Application CSS. Motion binds to component state and is not its to
      // declare. A token's value, a branch on the theme, a member's look and
      // the root's font size are the theme's decisions, not its own.
      files: ['**/*.css'],
      rules: {
        [RULE_NAMES.noMotionOutsideVocabulary]: true,
        [RULE_NAMES.noTokenDeclarations]: true,
        [RULE_NAMES.noAppThemeSelectors]: true,
        [RULE_NAMES.noAppMemberSelectors]: true,
        [RULE_NAMES.noRootFontSize]: true,
        // Every \`--pm-*\` read here must be one something declares. CSS answers
        // an unresolvable custom property by dropping the whole declaration, so
        // a single misremembered name takes a rule's other values with it,
        // silently. Applies to the vendored tree as well — overrides merge.
        [RULE_NAMES.noGhostTokens]: [true, { tokens: TOKENS }],
      },
    },
    {
      // The vendored vocabulary and its compiled theme: design decisions live
      // here, spelled as tokens. Last, so its \`null\`s lift the rules above.
      files: ['${dir}/**/*.css'],
      rules: {
        [RULE_NAMES.noMotionOutsideVocabulary]: null,
        [RULE_NAMES.noTokenDeclarations]: null,
        [RULE_NAMES.noAppThemeSelectors]: null,
        [RULE_NAMES.noAppMemberSelectors]: null,
        [RULE_NAMES.noRootFontSize]: null,
        [RULE_NAMES.tokenValuesOnly]: [true, { values: VALUES }],
        // \`--radix-*\` is geometry the positioning engine measures at runtime,
        // not a decision — a panel cannot honour "as wide as its trigger"
        // without one.
        'custom-property-pattern': '^(pm|radix)-[a-z0-9-]+$',
      },
    },
  ],
}
`
}

/** Whether a plan installs any theme data: a system, a palette, or both. */
export function hasTheme(plan: InstallPlan): boolean {
  return plan.systems.length > 0 || plan.palettes.length > 0
}

/**
 * Every generated file, as install-relative path -> contents.
 *
 * `tokens` is the registry's `theme.customProperties`, read from the catalogue
 * by a caller that has one, the same way as `theme.prepaint`. `values` is the
 * installed theme's (`tokenValuesIn`), read by a caller that has compiled it.
 * Both default to empty because one caller needs only the *keys*: `prune` asks
 * which paths an install still generates, and a path does not depend on the
 * file's contents.
 */
export function generatedFiles(
  plan: InstallPlan,
  dir: string,
  tokens: string[] = [],
  values: TokenValues = {},
): Record<string, string> {
  const files: Record<string, string> = {}

  if (plan.files.length > 0 || hasTheme(plan)) {
    files['polymorph.eslint.js'] = eslintFragment(
      dir,
      values,
      plan.framework === undefined ? {} : { framework: plan.framework },
    )
    files['polymorph.stylelint.js'] = stylelintFragment(dir, tokens, values)
  }
  if (hasTheme(plan)) {
    files[`${dir}/themes/index.ts`] = themeModule(
      plan.systems,
      plan.palettes,
      plan.base ? BASE_IMPORT : null,
    )
    // The installer compiles these from the JSON. This function only lists the paths.
    files[`${dir}/themes/${THEME_SHEET}`] = ''
    files[`${dir}/themes/${PREPAINT_MODULE}`] = ''
    for (const pairing of themePairings(plan.systems, plan.palettes)) {
      files[`${dir}/themes/${pairing.sheet}`] = ''
      files[`${dir}/themes/${pairing.loader}`] = pairingLoader(pairing.sheet)
    }
  }

  return files
}
