/**
 * The files `polymorph add` generates instead of copying.
 *
 * There are five, and the install does not work without each of them:
 *
 *  - `themes/index.ts`. Without it the system and palette are JSON files that
 *    nothing reads.
 *  - the font imports inside it. Without them the theme renders in its
 *    fallback font stack, which is a broken install.
 *  - `themes/prepaint.ts`, the pre-paint script built for the installed
 *    systems. The install inlines it in `index.html`; an application with no
 *    `index.html` (a Next.js root layout) imports it. Without it a system that
 *    opens dark paints light first.
 *  - `polymorph.eslint.js` / `polymorph.stylelint.js`. Without them the red
 *    rules run only in this repository. "Open code, closed usage" requires the
 *    usage to be governed in the consumer's repository.
 *
 * Generated files are recorded as generated in the manifest and rewritten on
 * every `add` and `update`. This keeps them out of `polymorph diff`. They are
 * outputs, and the next install overwrites any edit to one, so the diff would
 * otherwise report that edit permanently.
 */

const BANNER = (what: string, instead: string) =>
  `/* Generated by \`polymorph add\` — ${what}.\n * Rewritten on every install; ${instead}. */\n`

/**
 * How the generated module imports the base layer.
 *
 * A constant instead of a computed relative path, because the plan fixes both
 * ends. The module is always `<dir>/themes/index.ts` and the base layer is
 * always `<dir>/base.css`, whatever `--dir` the consumer chose.
 */
export const BASE_IMPORT = '../base.css'

/** The compiled stylesheet of every installed system paired with its own palette. */
export const THEME_SHEET = 'theme.css'

/** The module that exports the pre-paint script built for the installed systems. */
export const PREPAINT_MODULE = 'prepaint.ts'

/**
 * `themes/prepaint.ts`: the pre-paint script the install built from the
 * installed systems' default modes, as a string an application inlines first
 * in `<head>`. It imports nothing, so a server component can import it.
 */
export function prepaintModule(script: string): string {
  return [
    BANNER('the pre-paint script for the installed systems', 'run `polymorph update`'),
    '/**',
    ' * Inline it first in `<head>`, before any stylesheet. It applies the stored',
    ' * pairing and mode before the first paint, and for a reader who stored no mode',
    ' * the default mode of the system the page wears.',
    ' */',
    `export const PREPAINT_SCRIPT = ${JSON.stringify(script)}`,
    '',
  ].join('\n')
}

/**
 * Every pairing other than a system with its own palette, and the stylesheet
 * it compiles to. Each gets one small sheet, loaded the first time it is chosen.
 */
export function themePairings(
  systems: readonly SystemInstall[],
  palettes: readonly PaletteInstall[],
): { system: string; palette: string; sheet: string; loader: string }[] {
  const pairings: { system: string; palette: string; sheet: string; loader: string }[] = []
  for (const system of [...systems].sort((a, b) => a.name.localeCompare(b.name))) {
    for (const palette of [...palettes].sort((a, b) => a.name.localeCompare(b.name))) {
      if (palette.name === system.defaultPalette) continue
      const id = `${system.name}--${palette.name}`
      pairings.push({
        system: system.name,
        palette: palette.name,
        sheet: `pairings/${id}.css`,
        // A module that imports the sheet for its side effect. `import()` loads
        // this module, so the application needs no CSS type declaration.
        loader: `pairings/${id}.ts`,
      })
    }
  }
  return pairings
}

/** The module `ensurePairing` imports to load one pairing's sheet. */
export function pairingLoader(sheet: string): string {
  return `${BANNER('one pairing’s stylesheet, loaded on first choice', 'run `polymorph update`')}\nimport './${sheet.replace(/^pairings\//, '')}'\n`
}

/**
 * The theme module: the base layer, fonts, the compiled sheet, then hydration,
 * plus one entry point for the pairings that are not in the sheet.
 *
 * **Nothing here derives a theme.** The installer compiled every pairing to CSS
 * when it wrote this file (`theme.css` and `pairings/`). The application ships
 * stylesheets and a few hundred bytes of attribute-setting runtime, with no
 * theme engine, no schema library and no colour maths. After editing a system
 * or palette JSON, run `polymorph update` to recompile.
 *
 * **The base layer is first.** It is imported here because this is the one
 * module every consumer imports at their entry. The install patches
 * `src/main.tsx` to call `installThemes()`, so the base layer cannot be left
 * out. Vendored component files are deep-imported one at a time, and none of
 * them imports it.
 *
 * It comes before the theme sheet because of the cascade. The base layer binds
 * `body` to `--pm-text-md-*`, and the sheet supplies those values. The font
 * imports come next. They are side-effecting, because the `@font-face` rules
 * must exist before the sheet that names the families.
 *
 * `theme.css` covers every installed system paired with the palette it
 * declares, so switching between *those* is an attribute change. Every other
 * palette on every system has its own sheet, loaded by `ensurePairing`. Await
 * it before switching. Compiling the cross-product into one sheet would
 * multiply its size by the palette count for pairings nobody selected.
 */
export function themeModule(
  systems: SystemInstall[],
  palettes: PaletteInstall[],
  /**
   * The vendored base layer's path, or `null` when the install has none. On an
   * update, `null` means upstream dropped it, and importing a missing file
   * would break the consumer's build.
   */
  base: string | null = BASE_IMPORT,
  /**
   * Each system's `defaultMode`, read from the documents the install compiled.
   * A system it does not name follows the device.
   */
  modes: Readonly<Record<string, ModePreference>> = {},
): string {
  const orderedSystems = [...systems].sort((a, b) => a.name.localeCompare(b.name))
  const orderedPalettes = [...palettes].sort((a, b) => a.name.localeCompare(b.name))

  const fonts = [
    ...new Set(orderedSystems.flatMap((system) => system.fonts.map((font) => font.package))),
  ]
    .sort()
    .map((pkg) => {
      const families = orderedSystems
        .flatMap((system) => system.fonts)
        .filter((font) => font.package === pkg)
        .map((font) => font.family)
      return `import '${pkg}' // ${[...new Set(families)].join(', ')}`
    })

  const installed = new Set(orderedPalettes.map((palette) => palette.name))
  const resolvable = orderedSystems.filter((system) => installed.has(system.defaultPalette))
  const catalogue = {
    systems: Object.fromEntries(resolvable.map((system) => [system.name, system.defaultPalette])),
    palettes: orderedPalettes.map((palette) => palette.name),
    modes: Object.fromEntries(
      resolvable.map((system) => [system.name, modes[system.name] ?? 'system']),
    ),
  }
  const first = orderedSystems[0]?.name ?? ''

  return [
    BANNER(
      'the installed systems and palettes, compiled, and the webfonts they need',
      'edit the JSON and run `polymorph update`, not this file',
    ),
    '',
    ...(base === null
      ? []
      : [
          '// The base layer: box-sizing, the user agent’s off-scale margins removed,',
          '// and body type bound to the theme. First, so everything else may override it.',
          `import '${base}'`,
          '',
        ]),
    '// Apps load fonts; the library never bundles them. Side-effecting imports,',
    '// before the sheet that names the families.',
    ...fonts,
    '',
    '// Every installed system with its own palette, compiled when this file was written.',
    `import './${THEME_SHEET}'`,
    '',
    "import { getPalette, getSystem, hydrateTheme } from '@polymorph/engine/runtime'",
    '',
    `export const DEFAULT_SYSTEM = '${first}'`,
    '',
    '/**',
    ' * What hydration judges a stored choice against, which the staleness law needs both sets',
    ' * of, and the mode each system opens in for a reader who has not chosen one.',
    ' */',
    `const INSTALLED = ${JSON.stringify(catalogue)}`,
    '',
    '/** Every other pairing: its own sheet, fetched the first time it is chosen. */',
    'const PAIRINGS: Record<string, () => Promise<unknown>> = {',
    ...themePairings(orderedSystems, orderedPalettes).map(
      (pairing) =>
        `  '${pairing.system}/${pairing.palette}': () => import('./${pairing.loader.replace(/\.ts$/, '')}'),`,
    ),
    '}',
    '',
    '/** Call once, before the app mounts. */',
    'export function installThemes(): void {',
    `  hydrateTheme(${first === '' ? 'undefined' : 'DEFAULT_SYSTEM'}, INSTALLED)`,
    '  const system = getSystem()',
    '  const palette = getPalette()',
    '  if (system !== null && palette !== null) void ensurePairing(system, palette)',
    '}',
    '',
    '/**',
    ' * Any palette on any system. Await it before flipping `data-system` or',
    ' * `data-palette`, or the document wears a pair no stylesheet matches yet.',
    ' */',
    'export function ensurePairing(system: string, palette: string): Promise<void> {',
    '  const load = PAIRINGS[`${system}/${palette}`]',
    '  return load ? load().then(() => undefined) : Promise.resolve()',
    '}',
    '',
  ].join('\n')
}

