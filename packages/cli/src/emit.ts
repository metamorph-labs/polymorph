/**
 * The values a raw colour, length or duration is compared with, by family:
 * custom property -> value. It is the shape the rules take as their `values`
 * option (`TokenValues` in `@polymorph/rules/stylelint/emitted`), declared here
 * because this package does not depend on the rules.
 */
export interface TokenValues {
  color?: Record<string, string>
  space?: Record<string, string>
  radius?: Record<string, string>
  text?: Record<string, string>
  size?: Record<string, string>
  duration?: Record<string, string>
}

/**
 * The values in a compiled theme sheet, for the rules that name the nearest
 * token to a raw value.
 *
 * Read from the sheet's first block: the first pairing's base values, in its
 * default mode and at its system's own density, which is what the page renders
 * before any scope attribute applies. The families are chosen by the theme's own
 * role and step lists, so a colour that is not a role an application paints
 * with (a chart series) is never offered. This is the reading `tokenValues`
 * in `@polymorph/rules/stylelint/emitted` makes of this repository's reference
 * pairing. The installer makes it of the consumer's own compiled sheet, which
 * the rules cannot see at lint time, and `patch.test.ts` holds the two
 * readings to the same answer. A family with nothing in it is left out.
 */
export function tokenValuesIn(sheet: string): TokenValues {
  const end = sheet.indexOf('}')
  const base = end === -1 ? '' : sheet.slice(0, end)
  const declared = new Map(
    [...base.matchAll(/(--pm-[a-z0-9-]+)\s*:\s*([^;]+);/g)].map(
      (match) => [match[1] as string, (match[2] as string).trim()] as const,
    ),
  )

  const pick = (paths: readonly string[]): Record<string, string> => {
    const family: Record<string, string> = {}
    for (const name of paths.map(cssVarName)) {
      const value = declared.get(name)
      if (value !== undefined && !value.startsWith('var(')) family[name] = value
    }
    return family
  }

  const families: Required<TokenValues> = {
    color: pick(COLOR_ROLES),
    space: pick(SPACE_STEPS.map((step) => `space.${step}`)),
    radius: pick(RADIUS_STEPS.map((step) => `radius.${step}`)),
    text: pick([
      ...TEXT_STEPS.map((step) => `text.${step}.size`),
      ...DISPLAY_STEPS.map((step) => `display.${step}.size`),
    ]),
    size: pick([
      ...(['sm', 'md', 'lg'] as const).map((size) => `controlHeight.${size}`),
      ...ICON_SIZES.map((size) => `icon.size.${size}`),
    ]),
    duration: pick(DURATION_ROLES.map((role) => `motion.duration.${role}`)),
  }
  return Object.fromEntries(
    Object.entries(families).filter(([, family]) => Object.keys(family).length > 0),
  )
}

/** A string as a single-quoted JavaScript literal. */
const quoted = (text: string) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

/** `values` as an object literal, one token per line, for a generated config. */
function valuesLiteral(values: TokenValues): string {
  const families = Object.entries(values).filter(
    (entry): entry is [string, Record<string, string>] =>
      entry[1] !== undefined && Object.keys(entry[1]).length > 0,
  )
  if (families.length === 0) return '{}'

  const lines = ['{']
  for (const [family, tokens] of families) {
    lines.push(`  ${family}: {`)
    for (const [name, value] of Object.entries(tokens)) {
      lines.push(`    ${quoted(name)}: ${quoted(value)},`)
    }
    lines.push('  },')
  }
  lines.push('}')
  return lines.join('\n')
}

/** The comment above `VALUES` in every fragment, whichever command wrote it. */
const VALUES_DOC = `/**
 * What each token is worth in your installed theme, by family: what a rule
 * compares a raw colour, length or duration with, so its report names the
 * nearest token (\`12px\` is \`--pm-space-4\`) instead of only the family.
 *
 * They are the values of the first installed system with its own palette, in
 * its default mode and at the system's own density: what the page renders
 * before any scope attribute applies. \`polymorph add\` and \`polymorph update\`
 * read them from the theme sheet they compile. \`polymorph init\` writes the
 * registry's values for the same pairing, because its app compiles the theme
 * at build time. An install with no system of its own, such as an app that
 * builds its theme at run time, gets the registry's values for
 * \`${DEFAULT_SYSTEM}\` with its own palette: a report names the token nearest
 * the raw value there, which for anything but a space step can differ from the
 * token nearest it in your theme. Empty only when there was nothing to read:
 * the reports then name the family.
 */`

/** The first block of both ESLint fragments: the plugin, and a parser that reads TSX. */
const PLUGIN_BLOCK = `  {
    plugins: { [PLUGIN_NAME]: plugin },
    // Every rule below is syntactic — none asks the checker a question — but
    // they all need something that can read TSX, and ESLint's default cannot.
    // Set here so the rules work in a repository that has no parser configured.
    files: ['**/*.{ts,tsx}'],
    languageOptions: { parser, parserOptions: { ecmaFeatures: { jsx: true } } },
  },`

/**
 * The block a Vue app's fragments add: a `.vue` file read by the Vue parser,
 * with the TSX parser for its `<script setup>` and its template's expressions.
 * The rules read the template through the parser's services, so the same
 * rules govern a component's template as govern TSX.
 */
const VUE_BLOCK = `  {
    plugins: { [PLUGIN_NAME]: plugin },
    // A single-file component: its template through the Vue parser, its
    // \`<script setup>\` and the template's expressions through the TSX parser.
    files: ['**/*.vue'],
    languageOptions: {
      parser: vueParser,
      parserOptions: { parser, extraFileExtensions: ['.vue'] },
    },
  },`

/**
 * The block a Svelte app's fragments add: a `.svelte` file read by the Svelte
 * parser, with the TSX parser for its scripts and its markup's expressions.
 * The markup is part of the program the rules walk, so the same rules govern
 * a component's markup as govern TSX.
 */
const SVELTE_BLOCK = `  {
    plugins: { [PLUGIN_NAME]: plugin },
    // A Svelte component: its markup through the Svelte parser, its
    // \`<script lang="ts">\` and the markup's expressions through the TSX parser.
    files: ['**/*.svelte'],
    languageOptions: {
      parser: svelteParser,
      parserOptions: { parser, extraFileExtensions: ['.svelte'] },
    },
  },`

/** The line a Solid app's application block adds, so every TSX file reads as Solid. */
const SOLID_SETTINGS = `    // Every file is Solid TSX: \`class\`, \`onclick\` and \`on:click\` are read
    // as Solid reads them, and the icon fix imports \`Icon\` from \`@polymorph/solid\`.
    settings: solidSettings,`

/**
 * What an Angular app's fragments import beside the rules: the processor that
 * extracts a component's inline template, and the parser that reads a
 * template. The app installs both as dev dependencies.
 */
const ANGULAR_IMPORTS = `import angularTemplate from '@angular-eslint/eslint-plugin-template'
import templateParser from '@angular-eslint/template-parser'
`

/**
 * The rules an Angular app's two blocks share: every application rule, and
 * the two that report a raw colour or length given the theme's values.
 */
const ANGULAR_RULES = `/** Every application rule; the two that report a raw colour or length name the nearest token. */
const RULES = {
  ...allRules,
  [\`\${PLUGIN_NAME}/no-raw-styles\`]: ['error', { values: VALUES }],
  [\`\${PLUGIN_NAME}/no-app-css\`]: ['error', { values: VALUES }],
}`

/**
 * An Angular app's two application blocks. A module is read as Angular
 * (`angularSettings`), and the processor of
 * `@angular-eslint/eslint-plugin-template` hands each component's inline
 * template to the second block as a file of its own,
 * `<file>.ts/inline-template-<name>-<n>.component.html`. The second block
 * reads that template, and any `templateUrl` file, with Angular's template
 * parser, so the same rules govern a template as govern TypeScript. `ignores`
 * is the vendored tree's, when there is one.
 */
function angularBlocks(ignores: { code: string; templates: string } | null): string {
  const skip = (glob: string | undefined) => (glob === undefined ? '' : `\n    ignores: [${glob}],`)
  return `  {
    // Application code: composition and content bindings, nothing else. Every
    // module is read as Angular, and each component's inline template goes to
    // the block below.
    files: ['**/*.ts'],${skip(ignores?.code)}
    processor: angularTemplate.processors['extract-inline-html'],
    settings: angularSettings,
    rules: RULES,
  },
  {
    // A component's template, inline or in a \`templateUrl\` file, through
    // Angular's template parser: the same rules, read in template syntax.
    files: ['**/*.html'],${skip(ignores?.templates)}
    plugins: { [PLUGIN_NAME]: plugin },
    languageOptions: { parser: templateParser },
    settings: angularSettings,
    rules: RULES,
  },`
}

/** The options every fragment takes beside the values. */
export interface FragmentOptions {
  /**
   * The web framework the app is written in. `vue` and `svelte` add the block
   * that parses `.vue` or `.svelte` files and apply the rules to them. `solid`
   * reads every TSX file as Solid. `angular` reads every module as Angular and
   * each component's template through Angular's template parser. Default
   * `react`.
   */
  framework?: Framework
}

/** The two rules that report a raw colour or length, given the theme's values. */
const VALUED_RULES = `      // The two rules that report a raw colour or length name the nearest token.
      [\`\${PLUGIN_NAME}/no-raw-styles\`]: ['error', { values: VALUES }],
      [\`\${PLUGIN_NAME}/no-app-css\`]: ['error', { values: VALUES }],`

/**
 * The ESLint half, as a flat-config array that the consumer's config spreads.
 *
 * `values` is the installed theme's, read by `tokenValuesIn`. The two rules
 * that report a raw value take it, so a report names the nearest token and the
 * prop that carries it instead of only the family.
 *
 * Three blocks. The split between the second and third is the important part.
 * **Application code** gets every rule: it may not express a style decision
 * and may not reach past the vocabulary. **The vendored tree** gets none of
 * them, because it is the vocabulary now, and a component that could not
 * write a colour would be useless. It keeps the packaging-boundary rule,
 * re-rooted at the consumer's directory, so their copy of Button stays as
 * vendorable as ours. It may import `@polymorph/react` and its own siblings,
 * and nothing else.
 *
 * These two globs implement "open code, closed usage".
 */
export function eslintFragment(
  dir: string,
  values: TokenValues = {},
  options: FragmentOptions = {},
): string {
  if (options.framework === 'angular') return vendoringAngularEslintFragment(dir, values)
  const vue = options.framework === 'vue'
  const svelte = options.framework === 'svelte'
  // A vendoring Solid app reads its TSX as Solid. It gets no control fix,
  // for the reason above: its members are imported by path.
  const solid = options.framework === 'solid'
  const extensions = vue ? '{ts,tsx,vue}' : svelte ? '{ts,tsx,svelte}' : '{ts,tsx}'
  const imports = `allRules, parser, PLUGIN_NAME${solid ? ', solidSettings' : ''}`
  const markupParser = vue
    ? "import vueParser from 'vue-eslint-parser'\n"
    : svelte
      ? "import svelteParser from 'svelte-eslint-parser'\n"
      : ''
  const markupBlock = vue ? `\n${VUE_BLOCK}` : svelte ? `\n${SVELTE_BLOCK}` : ''
  return `${BANNER('the red rules, travelling with the install', 'put your own rules in your config, not here')}
import plugin, { ${imports} } from '@polymorph/rules/eslint'
${markupParser}
/** Yours to edit, and still not allowed to reach past the install boundary. */
const VENDORED = '${dir}/**/*.${extensions}'

${VALUES_DOC}
const VALUES = ${valuesLiteral(values)}

/** @type {import('eslint').Linter.Config[]} */
export default [
${PLUGIN_BLOCK}${markupBlock}
  {
    // Application code: composition and content bindings, nothing else.
    files: ['**/*.${extensions}'],
    ignores: [VENDORED],${solid ? `\n${SOLID_SETTINGS}` : ''}
    rules: {
      ...allRules,
${VALUED_RULES}
    },
  },
  {
    files: [VENDORED],
    rules: {
      [\`\${PLUGIN_NAME}/vendorable-imports\`]: ['error', { root: '${dir}' }],
    },
  },
]
`
}

/**
 * The ESLint half for an app that vendors Angular members: the Angular blocks,
 * which leave the vendored tree alone, and the vendored tree held to the
 * packaging boundary. The processor never reads a vendored module, so no
 * vendored template reaches the template block.
 */
function vendoringAngularEslintFragment(dir: string, values: TokenValues): string {
  return `${BANNER('the red rules, travelling with the install', 'put your own rules in your config, not here')}
import plugin, { allRules, angularSettings, parser, PLUGIN_NAME } from '@polymorph/rules/eslint'
${ANGULAR_IMPORTS}
/** Yours to edit, and still not allowed to reach past the install boundary. */
const VENDORED = '${dir}/**/*.ts'

${VALUES_DOC}
const VALUES = ${valuesLiteral(values)}

${ANGULAR_RULES}

/** @type {import('eslint').Linter.Config[]} */
export default [
${PLUGIN_BLOCK}
${angularBlocks({ code: 'VENDORED', templates: `'${dir}/**'` })}
  {
    files: [VENDORED],
    rules: {
      [\`\${PLUGIN_NAME}/vendorable-imports\`]: ['error', { root: '${dir}' }],
    },
  },
]
`
}

/**
 * The ESLint half for an app that installs \`@polymorph/react-ui\` instead of
 * vendoring it, as \`polymorph init\` writes one.
 *
 * It differs from \`eslintFragment\` in two ways. It spreads
 * \`fixableRawControls\` after the rules, because every member in such an app
 * is imported from \`@polymorph/react-ui\`. \`eslint --fix\` can then rewrite a
 * text-only \`<button>\` as \`Button\` and import it from there. The vendoring
 * fragment cannot, because a vendored app imports its members by path. It also
 * has no block for a vendored tree, because the app has none.
 */
export function installedEslintFragment(
  values: TokenValues = {},
  options: FragmentOptions = {},
): string {
  if (options.framework === 'vue') return installedVueEslintFragment(values)
  if (options.framework === 'svelte') return installedSvelteEslintFragment(values)
  if (options.framework === 'solid') return installedSolidEslintFragment(values)
  if (options.framework === 'angular') return installedAngularEslintFragment(values)
  return `/* Generated by \`polymorph init\` — the red rules for an app that installs the vocabulary.
 * Put your own rules in your config, not here. */

import plugin, { allRules, fixableRawControls, parser, PLUGIN_NAME } from '@polymorph/rules/eslint'

${VALUES_DOC}
const VALUES = ${valuesLiteral(values)}

/** @type {import('eslint').Linter.Config[]} */
export default [
${PLUGIN_BLOCK}
  {
    // Application code: composition and content bindings, nothing else. Its
    // members come from \`@polymorph/react-ui\`, so \`eslint --fix\` rewrites a
    // raw control that has one lawful member as that member, imported from there.
    files: ['**/*.{ts,tsx}'],
    rules: {
      ...allRules,
      ...fixableRawControls,
${VALUED_RULES}
    },
  },
]
`
}

/**
 * The ESLint half for a Vue app that installs \`@polymorph/vue-ui\`.
 *
 * It parses \`.vue\` files with \`vue-eslint-parser\`, which the app installs
 * as a dev dependency, and applies every application rule to them and to the
 * app's TypeScript. It spreads no \`fixableRawControls\`: those fixes write a
 * TSX member, and a Vue app's controls are in templates. The rules' one fix
 * that applies in a template, removing a \`class\` or \`style\` from a member,
 * needs no option.
 */
