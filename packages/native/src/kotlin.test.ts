/**
 * The Kotlin contracts in `platforms/android/ui/src/generated/kotlin`.
 *
 * They are committed, so a Gradle build needs no Node, and so they can fall
 * behind the registry they are generated from. The freshness law regenerates
 * them in memory and compares every file with the one on disk.
 *
 * The props the mapping cannot express are counted, as for Swift
 * (`contracts.test.ts`), and so are the opaque types: lower a number when the
 * mapping learns a type, and raise it only with the reason in the change. The
 * counts are Android's own, because Android renders fewer members: the charts
 * are absent there. ImageEditor's `Blob` is a `ByteArray`, as Swift holds it as
 * `Data`, so no type is opaque.
 */
const UNSUPPORTED_COUNT = 10
const OPAQUE_COUNT = 0

const ROOT = resolve(import.meta.dirname, '../../..')
const registry = buildRegistry(ROOT)
const sources = readKotlinMembers(ROOT)
const symbols = readMaterialSymbols(ROOT)
const reserved = readKotlinDeclaredTypes(ROOT)
const recipes = readRecipes(ROOT)
const set = generateKotlinContracts(registry, sources, symbols, reserved, recipes)

describe(`the generated Kotlin contracts (${KOTLIN_GENERATED})`, () => {
  it('are current: run `pnpm native:contracts` when this fails', () => {
    expect(
      staleFiles(ROOT, set.files, KOTLIN_GENERATED),
      'stale generated files: run `pnpm native:contracts`',
    ).toEqual([])
  })

  // It builds the registry again from the sources, which takes seconds on a busy machine.
  it('are deterministic: the same registry gives the same bytes', { timeout: 60_000 }, () => {
    expect(
      generateKotlinContracts(buildRegistry(ROOT), sources, symbols, reserved, recipes).files,
    ).toEqual(set.files)
  })

  it('name their generator, forbid hand edits, and declare the package', () => {
    for (const [name, contents] of Object.entries(set.files)) {
      expect(contents.startsWith(`// Generated by \`${KOTLIN_GENERATOR}\``), name).toBe(true)
      expect(contents, name).toMatch(/^\/\/ Never edit it by hand:/m)
      expect(contents, name).toMatch(/^package dev\.polymorph\.ui$/m)
    }
  })

  it('cover every member the Android platform map marks native or adapted, and no other', () => {
    const expected = [...registry.components, ...registry.exceptions.primitives]
      .filter((member) => member.platforms.android.status !== 'absent')
      .map((member) => member.name)
      .sort()
    expect(set.members.map((member) => member.name)).toEqual(expected)
    const contracts = set.files['Contracts.kt'] ?? ''
    for (const name of expected) {
      expect(contracts).toMatch(
        new RegExp(`(?:data )?class PM${name}Props(?:<\\w+(?:, \\w+)*>)?[ (\\n]`),
      )
      expect(contracts).toMatch(new RegExp(`(?:fun )?interface PM${name}Rendering \\{`))
    }
    for (const absent of ['BarChart', 'Command', 'Tooltip']) {
      expect(contracts).not.toContain(`PM${absent}Props`)
      expect(set.files['Catalogue.kt']).toContain(
        `PMCatalogueEntry(name = "${absent}", status = PMPlatformStatus.Absent`,
      )
    }
    expect(set.files['Catalogue.kt']).toContain(
      'PMCatalogueEntry(name = "Dialog", status = PMPlatformStatus.Adapted, rendersAs = ',
    )
  })

  it(`list ${UNSUPPORTED_COUNT} props the mapping cannot express yet, each with its TypeScript type`, () => {
    expect(set.unsupported.length).toBe(UNSUPPORTED_COUNT)
    for (const entry of set.unsupported) {
      expect(set.files['Unsupported.kt']).toContain(`class ${entry.kotlin}\n`)
      expect(set.files['Contracts.kt']).toContain(`: ${entry.kotlin}`)
    }
  })

  it(`hold ${OPAQUE_COUNT} named types opaque, and no member with a rendering reads one`, () => {
    expect(set.opaque.length).toBe(OPAQUE_COUNT)
    const drawn = new Set(sources.renderings)
    expect(
      set.opaque.flatMap((type) =>
        type.usedBy
          .filter((use) => drawn.has(use.split('.')[0] as string))
          .map((use) => `${use}: ${type.kotlin}`),
      ),
    ).toEqual([])
  })

  it('refuse a generated name a hand-written source or the token module declares', () => {
    expect(reserved).toContain('PMContent')
    expect(reserved).toContain('PMTheme')
    expect(reserved).toContain('PMSpecDefault')
    expect(() =>
      generateKotlinContracts(registry, sources, symbols, [...reserved, 'PMButtonProps']),
    ).toThrow(/Button declares PMButtonProps, which a hand-written source already declares/)
    // What a comment or a string names is not a declaration.
    expect(
      kotlinDeclaredTypesIn({
        'A.kt':
          '// class PMCommented\nval text = "object PMQuoted"\nprivate data class PMReal(val x: Int)',
      }),
    ).toEqual(['PMReal'])
  })

  it('register the states fixtures and the renderings the member files declare', () => {
    expect(sources.fixtures).toContain('BadgeStates')
    expect(sources.renderings).toContain('Badge')
    for (const fixture of sources.fixtures)
      expect(set.files['Fixtures.kt']).toContain(`        ${fixture},\n`)
    for (const member of sources.renderings) {
      expect(set.files['Members.kt']).toMatch(new RegExp(`\\nfun (?:<\\w+> )?PM${member}\\(`))
      expect(set.files['Members.kt']).toContain(`    PM${member}.Render(`)
    }
    expect(
      kotlinFixturesIn({
        'A.kt': 'object BadgeStates : PMStates {}\n// object GhostStates : PMStates',
      }),
    ).toEqual(['BadgeStates'])
    expect(
      renderingsIn({
        'A.kt': 'object PMBadge : PMBadgeRendering {}\nobject PMCard : PMBadgeRendering {}',
      }),
    ).toEqual(['Badge'])
  })

  it('give every icon role its Material Symbols name from design/icons.json, and refuse a role without one', () => {
    const roles = registry.icons.roles.map((role) => role.name)
    expect(Object.keys(symbols).sort()).toEqual([...roles].sort())
    const contracts = set.files['Contracts.kt'] ?? ''
    expect(contracts).toContain(
      'enum class PMIconRole(val value: String, val symbolName: String) {',
    )
    expect(contracts).toContain('    Add("add", "add"),\n')
    expect(contracts).toContain('    SortAsc("sort-asc", "arrow_upward"),\n')
    expect(contracts.match(/^ {4}\w+\("[^"]+", "[a-z0-9_]+"\),$/gm)).toHaveLength(roles.length)
    const icons = set.files['Icons.kt'] ?? ''
    expect(icons).toContain('        PMIconRole.Add -> Icons.Outlined.Add\n')
    expect(icons).toContain('        PMIconRole.Back -> Icons.AutoMirrored.Outlined.ArrowBack\n')
    expect(icons).toContain(
      'import androidx.compose.material.icons.automirrored.outlined.ArrowBack\n',
    )
    for (const symbol of MIRRORED_SYMBOLS) expect(Object.values(symbols), symbol).toContain(symbol)
    expect(icons).toContain('        PMIconRole.Rating -> Icons.Filled.Star\n')
    expect(icons).toContain('import androidx.compose.material.icons.filled.Star\n')
    for (const symbol of FILLED_SYMBOLS.keys())
      expect(Object.values(symbols), symbol).toContain(symbol)

    const withoutAdd = Object.fromEntries(
      Object.entries(symbols).filter(([role]) => role !== 'add'),
    )
    expect(() => generateKotlinContracts(registry, sources, withoutAdd)).toThrow(
      /no Material Symbols name for the icon role add: give each role an "android" in design\/icons\.json/,
    )
    expect(() =>
      generateKotlinContracts(registry, sources, { ...symbols, gadget: 'settings' }),
    ).toThrow(/a Material Symbols name for gadget, which is no icon role/)
  })

  it("Button's contract", () => {
    expect(set.contracts.Button).toMatchSnapshot()
  })

  it("Dialog's contract", () => {
    expect(set.contracts.Dialog).toMatchSnapshot()
  })

  it("DataTable's contract, generic over its row type", () => {
    expect(set.contracts.DataTable).toMatchSnapshot()
  })
})

describe('the Kotlin mapping', () => {
  const contracts = set.contracts
  const field = (member: string, declaration: string) =>
    expect(contracts[member], member).toContain(`    val ${declaration},\n`)

  it('maps the scalars, and keeps a required prop required and an optional one defaulted', () => {
    field('Link', 'href: String')
    field('Progress', 'value: Double')
    field('Button', 'disabled: Boolean? = null')
    field('Button', 'label: String')
  })

  it('maps a literal union to an enum class, and the shared scales to their shared types', () => {
    field('Badge', 'tone: PMBadgeTone? = null')
    expect(contracts.Badge).toContain('enum class PMBadgeTone(val value: String) {\n')
    expect(contracts.Badge).toContain('    Neutral("neutral"),\n')
    field('Button', 'size: PMControlSize? = null')
    field('Button', 'icon: PMIconRole? = null')
    field('Grid', 'columns: PMGridColumns? = null')
    expect(contracts.Grid).toContain(
      'enum class PMGridColumns(val value: Int) {\n    Columns1(1),\n',
    )
    for (const [member, prop] of [
      ['Stack', 'gap'],
      ['Grid', 'gap'],
      ['Inline', 'py'],
      ['Skeleton', 'size'],
    ] as const)
      field(member, `${prop}: PMSpaceStep? = null`)
    field('Stack', '`as`: PMStackAs? = null')
    expect(contracts.Skeleton).toContain('    TextStep2xl("2xl"),\n')
    expect(contracts.Skeleton).toContain('    Width10("10"),\n    Full("full"),\n}')
  })

  it('maps a grid to one enum of its lawful cells, in place of the variant and the tone', () => {
    field('Button', 'appearance: PMButtonAppearance? = null')
    expect(contracts.Button).not.toMatch(/val (?:variant|tone): PMButton(?:Variant|Tone)\?/)
    expect(contracts.Button).toContain(
      '    OutlineNeutral("outline/neutral", PMButtonVariant.Outline, PMButtonTone.Neutral),\n',
    )
    expect(contracts.Button).not.toContain('SolidNeutral')
    expect(contracts.Button).toContain('        val lawful: List<PMButtonAppearance> = listOf(\n')
    expect(contracts.Button).toContain(
      '        fun of(variant: PMButtonVariant, tone: PMButtonTone): PMButtonAppearance? =\n',
    )
  })

  it('maps content, lists, functions, nullable values and named object types', () => {
    field('Dialog', 'children: PMContent? = null')
    field('Dialog', 'trigger: PMContent? = null')
    field('MultiSelect', 'value: List<String>? = null')
    // A DOM event has no native meaning, so its parameter is left out and the rest kept.
    field('Button', 'onClick: (() -> Unit)? = null')
    field('Input', 'onChange: ((String) -> Unit)? = null')
    field('Input', 'onBlur: (() -> Unit)? = null')
    field('Pagination', 'onPageChange: (Double) -> Unit')
    // Null is a value and omission another: an optional prop that takes null has two levels.
    field('Select', 'value: PMSome<String?>? = null')
    field('Select', 'onChange: ((String?) -> Unit)? = null')
    field('Select', 'options: List<PMSelectOptionEntry>')
    field('Toast', 'action: PMToastAction? = null')
    field('DataTable', 'emptyState: PMEmptyStateProps')
    // A name in `JSON_TYPES` crosses as the JSON an app stored: the document, and an entity's marks.
    field('RichTextContent', 'value: PMJSONValue')
    expect(set.files['Contracts.kt']).toContain(
      'data class PMRichTextEntity(\n    /** The app’s name for the kind of thing: `user`, `issue`. */\n',
    )
    expect(set.files['Contracts.kt']).toContain('    val marks: List<PMJSONValue>? = null,\n')
  })

  it('maps a function that returns an element to a composable slot of its parameters', () => {
    const file = set.files['Contracts.kt'] ?? ''
    expect(file).toContain('data class PMDataTableColumn<Row>(\n')
    expect(file).toContain('    val value: (Row) -> String,\n')
    expect(file).toContain('    val cell: (@Composable (Row) -> Unit)? = null,\n')
  })

  it('maps a union UNIONS names to an enum class or a sealed interface', () => {
    field('Checkbox', 'checked: PMCheckedState? = null')
    field('Checkbox', 'onCheckedChange: ((PMCheckedState) -> Unit)? = null')
    const file = set.files['Contracts.kt'] ?? ''
    expect(file).toContain(
      'enum class PMCheckedState {\n    Unchecked,\n    Checked,\n    Indeterminate,\n}',
    )
    expect(file).toMatch(
      /sealed interface PMSelectOptionEntry \{\n {4}data class Option\(val value: PMSelectOption\) : PMSelectOptionEntry\n(?: {4}\/\*\*.*\n)* {4}data class Group\(val value: PMSelectOptionGroup\) : PMSelectOptionEntry\n\}/,
    )
  })

  it('makes a member with a type parameter generic, and its rendering function with it', () => {
    expect(contracts.DataTable).toContain('data class PMDataTableProps<Row>(\n')
    field('DataTable', 'columns: List<PMDataTableColumn<Row>>')
    field('DataTable', 'data: List<Row>')
    field('DataTable', 'getRowId: (Row) -> String')
    field('DataTable', 'onRowClick: ((Row) -> Unit)? = null')
    field('DataTable', 'selection: Set<String>? = null')
    expect(contracts.DataTable).toContain(
      'interface PMDataTableRendering {\n    @Composable\n    fun <Row> Render(props: PMDataTableProps<Row>)\n}',
    )
    expect(contracts.Button).toContain(
      'fun interface PMButtonRendering {\n    @Composable\n    fun Render(props: PMButtonProps)\n}',
    )
  })

  it('adds the load status every page archetype but AppShell draws, first, and its retry', () => {
    for (const page of [
      'AuthPage',
      'ConversationPage',
      'Dashboard',
      'DetailPage',
      'FormPage',
      'ListPage',
      'MasterDetailPage',
      'SearchPage',
      'SettingsPage',
    ]) {
      expect(contracts[page], page).toMatch(
        /data class PM\w+Props\(\n(?: {4}(?:\/\*\*| \*| \*\/).*\n)* {4}val loadStatus: PMLoadStatus,\n/,
      )
    }
    field('ListPage', 'onRetry: (() -> Unit)? = null')
    expect(contracts.AppShell).not.toContain('loadStatus')
    expect(contracts.ListPage).not.toContain('val empty:')
    field('ListPage', 'emptyState: PMEmptyStateProps')
  })

  it('gives each shape a data class and each named literal union one enum', () => {
    const file = set.files['Contracts.kt'] ?? ''
    for (const name of Object.keys(SHAPES)) {
      if (!file.includes(`PM${name}`)) continue
      expect(file.match(new RegExp(`data class PM${name}\\b`, 'g')), name).toHaveLength(1)
    }
    expect(file).toContain('enum class PMSpaceStep(val value: Int) {\n    S0(0),\n')
    expect(file).toContain('enum class PMSortDirection(val value: String) {\n    Asc("asc"),\n')
  })

  it('writes a slash and a star in a doc comment as an entity, so a KDoc does not nest', () => {
    const file = set.files['Contracts.kt'] ?? ''
    expect(file).toContain('image/&#42;')
    const comments = file.match(/\/\*\*[\s\S]*?\*\//g) ?? []
    expect(comments.filter((comment) => comment.slice(2).includes('/*'))).toEqual([])
  })

  const member = (name: string, props: Registry['components'][number]['props']) => ({
    name,
    tier: 'structure',
    platforms: {
      web: { status: 'native' },
      ios: { status: 'native' },
      android: { status: 'native' },
    },
    purpose: 'A test member.',
    spec: null,
    props,
    grid: null,
  })
  const fake = (components: unknown[]) =>
    ({
      components,
      exceptions: { primitives: [] },
      icons: { roles: [] },
      theme: { scales: {} },
    }) as unknown as Registry

  it('leaves DOM event parameters out, escapes keywords, and spells tuples as pairs', () => {
    const contract = generateKotlinContracts(
      fake([
        member('Probe', [
          {
            name: 'onKey',
            type: '(value: string, event: KeyboardEvent<HTMLElement>) => void',
            optional: false,
          },
          { name: 'in', type: '"a-b" | "c"', optional: false },
          { name: 'range', type: '[number, number]', optional: true },
          { name: 'note', type: '(text: string) => ReactNode', optional: true },
          { name: 'label', type: 'string | null', optional: false },
          { name: 'aside', type: '(text: string) => ReactNode | undefined', optional: true },
        ]),
      ]),
      { fixtures: [], renderings: ['Probe'] },
      {},
    )
    const probe = contract.contracts.Probe ?? ''
    expect(probe).toContain('    val onKey: (String) -> Unit,\n')
    expect(probe).toContain('    val `in`: PMProbeIn,\n')
    expect(probe).toContain('    AB("a-b"),\n')
    expect(probe).toContain('    val range: Pair<Double, Double>? = null,\n')
    expect(probe).toContain('    val note: (@Composable (String) -> Unit)? = null,\n')
    expect(probe).toContain('    val label: String?,\n')
    // A slot draws nothing where the web returns nothing, so an optional
    // content result is a composable slot too.
    expect(probe).toContain('    val aside: (@Composable (String) -> Unit)? = null,\n')
    expect(contract.files['Members.kt']).toContain(
      '    PMProbe.Render(PMProbeProps(onKey = onKey, `in` = `in`, range = range, note = note, label = label, aside = aside))\n',
    )
  })

  it('maps a file to PMFile and an unknown value to PMJSONValue, the foundation’s types', () => {
    const contract = generateKotlinContracts(
      fake([
        member('Probe', [
          { name: 'upload', type: 'File', optional: false },
          { name: 'uploads', type: 'File[]', optional: true },
          { name: 'data', type: 'unknown', optional: false },
          { name: 'onPick', type: '(file: File) => void', optional: true },
        ]),
      ]),
      { fixtures: [], renderings: [] },
      {},
    )
    const probe = contract.contracts.Probe ?? ''
    expect(probe).toContain('    val upload: PMFile,\n')
    expect(probe).toContain('    val uploads: List<PMFile>? = null,\n')
    expect(probe).toContain('    val data: PMJSONValue,\n')
    expect(probe).toContain('    val onPick: ((PMFile) -> Unit)? = null,\n')
    expect(contract.unsupported).toEqual([])
  })

  it('holds a part to the member’s type parameters: a part prop that uses one is unsupported', () => {
    const contract = generateKotlinContracts(
      fake([
        member('Probe', [
          { name: 'rows', type: 'Row[]', optional: false },
          // Passed as a type argument and used alone, `Row` is the member's type parameter.
          { name: 'chosen', type: 'ReadonlySet<Row>', optional: true },
          { name: 'Group.title', type: 'string', optional: false },
          { name: 'Group.row', type: 'Row', optional: true },
        ]),
      ]),
      { fixtures: [], renderings: ['Probe'] },
      {},
    )
    const probe = contract.contracts.Probe ?? ''
    expect(probe).toContain('data class PMProbeProps<Row>(\n')
    expect(probe).toContain('    fun <Row> Render(props: PMProbeProps<Row>)\n')
    // The mapping gives a part's props no type parameters, so its function takes none.
    expect(probe).toContain('    fun RenderGroup(props: PMProbeGroupProps)\n')
    expect(contract.unsupported.map((entry) => `${entry.member}.${entry.prop}`)).toEqual([
      'Probe.Group.row',
    ])
    expect(contract.unsupported[0]?.reason).toMatch(/a part's props are not generic/)
  })

  it('draws a compound part by a function of the member’s rendering, and gives it a composable', () => {
    const contract = generateKotlinContracts(
      fake([
        member('Probe', [
          { name: 'label', type: 'string', optional: false },
          { name: 'Group.title', type: 'string', optional: true },
          { name: 'Group.children', type: 'ReactNode', optional: false },
        ]),
      ]),
      { fixtures: [], renderings: ['Probe'] },
      {},
    )
    const probe = contract.contracts.Probe ?? ''
    // A rendering with a part is no `fun interface`: it declares a function per part.
    expect(probe).toContain(
      'interface PMProbeRendering {\n    @Composable\n    fun Render(props: PMProbeProps)\n\n',
    )
    expect(probe).not.toContain('fun interface PMProbeRendering')
    expect(probe).toContain('    @Composable\n    fun RenderGroup(props: PMProbeGroupProps)\n}')
    const members = contract.files['Members.kt'] ?? ''
    // The screen emitter joins a part's name to its member's: `PMProbeGroup`.
    expect(members).toContain(
      '@Composable\nfun PMProbeGroup(\n    title: String? = null,\n    children: PMContent,\n) {\n' +
        '    PMProbe.RenderGroup(PMProbeGroupProps(title = title, children = children))\n}\n',
    )
    // An undrawn member's parts get no composable.
    const undrawn = generateKotlinContracts(
      fake([member('Probe', [{ name: 'Group.title', type: 'string', optional: true }])]),
      { fixtures: [], renderings: [] },
      {},
    )
    expect(undrawn.files['Members.kt']).not.toContain('PMProbeGroup')
  })
})

