#!/usr/bin/env node
import { mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { createJiti } from 'jiti'

/**
 * `pnpm shells` writes every framework's shell from the member descriptions in
 * `packages/shells/src/members/`: for Vue, Svelte, Solid and Angular, each
 * member's component and states fixture in `packages/<framework>-ui/src`, the
 * vocabulary's index and galleries, and the foundation's Icon, glyph data and
 * Icon stylesheet; for the elements, each native member's custom element
 * definition and its states fixture in element form. Each framework is a target (`TARGETS` in
 * `packages/shells/src/generate.ts`).
 *
 * `pnpm shells --target <name>` writes, or checks, one target's files and
 * nothing else.
 *
 * `pnpm shells --check` writes nothing. It exits 1 and names each file that is
 * missing, stale, or generated by no description, which is what the freshness
 * law (`packages/shells/src/shells.test.ts`) asserts.
 *
 * A generated file carries a header that says so. Write mode deletes a
 * generated file no description produces any more, in the trees of the targets
 * it writes; it never touches a file without the header.
 */

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..')
const args = process.argv.slice(2)
const check = args.includes('--check')
const at = args.indexOf('--target')
const named = at === -1 ? undefined : args[at + 1]
if (at !== -1 && (named === undefined || named.startsWith('--'))) {
  console.error('shells: --target takes a target name, such as `--target vue`')
  process.exit(1)
}

const jiti = createJiti(import.meta.url)
const { generateShells, generatedOnDisk, staleness, targetNamed, TARGETS } = await jiti.import(
  resolve(ROOT, 'packages/shells/src/generate.ts'),
)

let targets = TARGETS
if (named !== undefined) {
  try {
    targets = [targetNamed(named)]
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error))
    process.exit(1)
  }
}

const files = await generateShells(ROOT, undefined, undefined, targets)

if (check) {
  const faults = staleness(ROOT, files, targets)
  if (faults.length > 0) {
    console.error(`shells: ${faults.length} generated file(s) out of date — run \`pnpm shells\`:`)
    for (const fault of faults) console.error(`  ${fault}`)
    process.exit(1)
  }
  console.log(`shells: ${files.size} generated files are fresh`)
} else {
  for (const [path, text] of files) {
    const file = resolve(ROOT, path)
    mkdirSync(dirname(file), { recursive: true })
    writeFileSync(file, text)
  }
  for (const path of generatedOnDisk(ROOT, targets)) {
    if (!files.has(path)) {
      rmSync(resolve(ROOT, path))
      console.log(`shells: removed ${path}, which no description generates`)
    }
  }
  console.log(`shells: wrote ${files.size} files`)
}
