const QUOTED = /^"((?:[^"\\]|\\.)*)"$|^'((?:[^'\\]|\\.)*)'$/
const NUMERAL = /^-?\d+(\.\d+)?$/
const TEMPORAL = /^(Time|CalendarDate|CalendarDateTime|DateRange)$/
const REF = /^(React\.)?(Ref|RefObject|MutableRefObject|RefCallback)\b/

/** A union part without the parentheses that wrap it. */
function bare(part: string): string {
  let text = part.trim()
  while (text.startsWith('(') && text.endsWith(')') && !/^\([^()]*\)\s*=>/.test(text)) {
    text = text.slice(1, -1).trim()
  }
  return text
}

/**
 * The codec a value prop's attribute reads through, from the prop's type as
 * the registry prints it: a function or a ref is a property only, a date or a
 * time its ISO text, a set a JSON array of its members, data JSON, and a
 * union of literals each literal, with its open members (`string`, `number`,
 * `boolean`, data) after them.
 */
export function codecOf(type: string): Codec {
  let string = false
  let number = false
  let boolean = false
  let json = false
  let set = false
  const literals: (string | number)[] = []
  const temporal = new Set<string>()
  for (const part of unionParts(type).map(bare)) {
    if (part === 'null') continue
    if (part === 'string') string = true
    else if (part === 'number') number = true
    else if (part === 'boolean' || part === 'true' || part === 'false') boolean = true
    else if (QUOTED.test(part)) literals.push(JSON.parse(`"${part.slice(1, -1)}"`) as string)
    else if (NUMERAL.test(part)) literals.push(Number(part))
    else if (isFunctionType(part) || REF.test(part)) return 'property'
    else if (TEMPORAL.test(part)) temporal.add(part)
    else if (/^(Readonly)?Set</.test(part)) set = true
    else json = true
  }
  if (set) {
    if (string || number || boolean || json || literals.length > 0 || temporal.size > 0) {
      throw new Error(
        `shells: the elements renderer reads no set mixed with other values (${type})`,
      )
    }
    return 'set'
  }
  if (temporal.size > 0) {
    if (string || number || boolean || json || literals.length > 0) {
      throw new Error(
        `shells: the elements renderer reads no date mixed with other values (${type})`,
      )
    }
    if (temporal.has('DateRange')) return { temporal: 'range' }
    if (temporal.has('Time')) return { temporal: 'time' }
    return { temporal: 'date' }
  }
  // String literals read as their text and number literals as a number: the element hands the
  // member the value, and the member's type says which values it takes. A union that mixes the
  // two, or holds a boolean or data, keeps its literals, so `"12"` and `12` stay apart and
  // `checked="indeterminate"` is not read as `true`.
  const strings = literals.some((literal) => typeof literal === 'string')
  const numbers = literals.some((literal) => typeof literal === 'number')
  let kept = literals
  if (!(strings && numbers) && !boolean && !json) {
    if (strings && !number) string = true
    if (numbers && !string) number = true
    if ((strings && !number) || (numbers && !string)) kept = []
  }
  if (kept.length === 0) {
    const open = [string, number, boolean, json].filter(Boolean).length
    if (open === 0 || (open === 1 && string)) return 'string'
    if (open === 1 && number) return 'number'
    if (open === 1 && boolean) return 'boolean'
    if (open === 1 && json) return 'json'
  }
  return {
    union: kept,
    ...(string ? { string: true as const } : {}),
    ...(number ? { number: true as const } : {}),
    ...(boolean ? { boolean: true as const } : {}),
    ...(json ? { json: true as const } : {}),
  }
}

