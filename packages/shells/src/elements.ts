/**
 * The elements renderer: each member the elements map marks native
 * (`design/frameworks/elements.json`) as a custom element over its generated
 * Solid member, with its states fixture in element form.
 *
 * The elements are a distribution of the Solid rendering, not a rendering of
 * their own: a definition module names the Solid member and says how the
 * element reads its props, dispatches its events and fills its slots, and
 * writes no anatomy. What a prop is comes from the registry through
 * `vueBinding` (`@polymorph/registry/frameworks`), as for every shell: a value
 * prop is an attribute and a property, read through the codec its type takes
 * (`@polymorph/elements/codecs`); an `onFoo` prop is the `poly-foo` event; a
 * node prop is a slot, filled by the element's children; a render prop, a
 * function and a ref are properties only.
 *
 * The files: a definition module per member and per public part, a states
 * fixture per member, the vocabulary's index, its galleries, and the table of
 * every definition (`definitions.ts`), which reads no member. `Icon`'s
 * element ships in the foundation, as `Icon` ships in every foundation.
 *
 * Output is deterministic: the same descriptions, map and registry give the
 * same bytes, which the freshness law (`shells.test.ts`) relies on.
 */

