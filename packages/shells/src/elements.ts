let methods: ReadonlySet<string> | null = null

/**
 * The methods an element inherits from `HTMLElement`, by name, read from the
 * DOM's declarations in TypeScript's `lib.dom.d.ts`: what the bridge's
 * `inheritedMethod` finds on the prototype chain at run time. A prop of one of
 * these names has no property on its element, so the element's type leaves it
 * out. An accessor (`id`, `title`, `ariaLabel`) is not a method.
 */
export function elementMethods(): ReadonlySet<string> {
  if (methods !== null) return methods
  const file = '/element-methods.ts'
  const options: ts.CompilerOptions = {
    lib: ['lib.es2023.d.ts', 'lib.dom.d.ts'],
    types: [],
    noEmit: true,
  }
  const host = ts.createCompilerHost(options)
  const getSourceFile = host.getSourceFile.bind(host)
  host.getSourceFile = (name, language, ...rest) =>
    name === file
      ? ts.createSourceFile(name, 'export declare const element: HTMLElement\n', language)
      : getSourceFile(name, language, ...rest)
  const checker = ts.createProgram([file], options, host).getTypeChecker()
  const symbol = checker.resolveName('HTMLElement', undefined, ts.SymbolFlags.Type, false)
  if (symbol === undefined) throw new Error('shells: lib.dom.d.ts declares no HTMLElement')
  methods = new Set(
    checker
      .getPropertiesOfType(checker.getDeclaredTypeOfSymbol(symbol))
      .filter((property) => (property.flags & ts.SymbolFlags.Method) !== 0)
      .map((property) => property.name),
  )
  return methods
}

/** What the renderer knows about one element: its definition, and what its type and fixtures read. */
export interface ElementShape {
  /** The component's name: `Button`, `TabsContent`. */
  component: string
  definition: ElementDefinition
  /**
   * The props the element's type names as properties, by their React names:
   * every value prop, except one whose name is a method the element inherits,
   * which only its attribute sets.
   */
  properties: string[]
  /** The event props the member requires, which a fixture handles. */
  required: string[]
}

/** The events a description reads `listening` for, by their event props' names (`onDismiss`). */
function listenedEvents(sources: unknown): Set<string> {
  const text = JSON.stringify(sources)
  return new Set(
    [...text.matchAll(/\blistening\.(\w+)/g)].map((match) => `on${capital(match[1] ?? '')}`),
  )
}

/** The slots the anatomy renders only inside a portal, by their React names. */
function overlaySlots(template: MemberShell['template']): string[] {
  const found = new Set<string>()
  const visit = (nodes: readonly Node[], inPortal: boolean) => {
    for (const node of nodes) {
      if (node.kind === 'slot' && inPortal)
        found.add(node.name === 'default' ? 'children' : node.name)
      for (const list of childLists(node)) visit(list, inPortal || node.kind === 'portal')
    }
  }
  visit(Array.isArray(template) ? (template as readonly Node[]) : [template as Node], false)
  return [...found].sort()
}

/**
 * An element's shape: the registry's props read by `vueBinding`, the events
 * the description asks whether its caller handles, and, for a public part
 * whose one element must be a direct child of its parent's, that it is
 * structural.
 */
export function elementShape(
  component: RegistryMemberLike,
  sources: unknown,
  template: MemberShell['template'],
  structural: boolean,
  options: { types?: DataTypes; within?: string } = {},
): ElementShape {
  const listened = listenedEvents(sources)
  const props: Record<string, Codec> = {}
  const events: Record<string, ElementEvent> = {}
  const slots: string[] = []
  const properties: string[] = []
  const required: string[] = []
  const fields: Record<string, string[]> = {}
  const callbacks: Record<string, ElementCallback[]> = {}
  const own = component.props.filter((prop) => !prop.name.includes('.'))
  for (const prop of own) {
    const binding = vueBinding(prop)
    if (binding.kind === 'event') {
      events[prop.name] = {
        type: eventOf(prop.name),
        ...(listened.has(prop.name) ? { listened: true as const } : {}),
      }
      if (!prop.optional) required.push(prop.name)
    } else if (binding.kind === 'slot') {
      slots.push(prop.name)
    } else {
      let codec = binding.kind === 'scoped-slot' ? 'property' : codecOf(prop.type)
      const data = codec === 'json' || (typeof codec === 'object' && 'union' in codec && codec.json)
      if (data && options.types !== undefined) {
        // Data an attribute's JSON cannot complete is a property only: a formatter in a messages
        // catalogue, a function a value is. Callbacks its items need are completed with events,
        // and node fields of its object are filled by dotted slots.
        const shape = dataShape(prop.type, options.types)
        if (shape.functions) codec = 'property'
        else {
          if (shape.nodes.length > 0) fields[prop.name] = shape.nodes
          if (shape.callbacks.length > 0) {
            callbacks[prop.name] = shape.callbacks.map((callback) => ({
              ...callback,
              type: eventOf(callback.name),
            }))
          }
        }
      }
      props[prop.name] = codec
      if (!elementMethods().has(propertyOf(prop.name))) properties.push(prop.name)
      else if (codec === 'property') {
        throw new Error(
          `shells: ${component.name}.${prop.name} is set from script only, and its name is a method every element inherits, which its property would hide`,
        )
      }
    }
  }
  // An item's callback dispatches its event on the element, so the member's own events take no
  // event of the same type.
  for (const [prop, list] of Object.entries(callbacks)) {
    for (const callback of list) {
      const clash = Object.entries(events).find(([, event]) => event.type === callback.type)
      if (clash !== undefined) {
        throw new Error(
          `shells: ${component.name}.${prop}'s items dispatch ${callback.type}, which is also ${component.name}.${clash[0]}'s event`,
        )
      }
    }
  }
  // The rule a screen drawn at run time follows too (`@polymorph/screen`).
  const controlled = controlledProps(own)
  const overlays = overlaySlots(template)
  const definition: ElementDefinition = {
    tag: tagOf(component.name),
    member: component.name,
    props,
    events,
    slots,
    ...(Object.keys(fields).length > 0 ? { fields } : {}),
    ...(Object.keys(callbacks).length > 0 ? { callbacks } : {}),
    ...(Object.keys(controlled).length > 0 ? { controlled } : {}),
    ...(structural ? { structural: true as const } : {}),
    ...(options.within !== undefined ? { within: options.within } : {}),
    ...(overlays.length > 0 ? { overlays } : {}),
  }
  return { component: component.name, definition, properties, required }
}

/** A description's own sources, without its parts and its fixture: what its expressions read. */
const memberSources = (shell: MemberShell) => ({ ...shell, parts: undefined, states: undefined })

/** Every element the vocabulary ships, by component name: each member and each public part. */
export function elementShapes(
  registry: Registry,
  shells: readonly MemberShell[],
  types?: DataTypes,
): Map<string, ElementShape> {
  const shapes = new Map<string, ElementShape>()
  for (const shell of shells) {
    const component = registryMember(registry, shell.member)
    shapes.set(
      shell.member,
      elementShape(component, memberSources(shell), shell.template, false, {
        ...(types !== undefined ? { types } : {}),
      }),
    )
    for (const part of shell.parts ?? []) {
      if (!part.public) continue
      const rendered = partShell(shell, part, component)
      const tag = hostElement(part.template)?.element.tag
      const structural = typeof tag === 'string' && STRUCTURAL_TAGS.has(tag)
      shapes.set(
        rendered.component.name,
        elementShape(rendered.component, part, part.template, structural, {
          ...(types !== undefined ? { types } : {}),
          within: tagOf(shell.member),
        }),
      )
    }
  }
  return shapes
}

