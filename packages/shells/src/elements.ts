/** A definition as TypeScript, with its keys quoted only where they must be. */
function definitionLiteral(definition: ElementDefinition): string {
  const value = (data: unknown): string => {
    if (Array.isArray(data)) return `[${data.map(value).join(', ')}]`
    if (data !== null && typeof data === 'object') {
      return `{ ${Object.entries(data as Record<string, unknown>)
        .map(([name, entry]) => `${key(name)}: ${value(entry)}`)
        .join(', ')} }`
    }
    return typeof data === 'string' ? jsString(data) : JSON.stringify(data)
  }
  return value(definition)
}

/** The element's type: the base class with a property for each prop, typed by the Solid member's props. */
function elementType(shape: ElementShape, props: string, generic: string | undefined): string {
  if (shape.properties.length === 0) return 'PolyElement'
  const parameters = typeParameters(generic)
  const typed =
    parameters.length === 0 ? props : `${props}<${parameters.map(() => 'unknown').join(', ')}>`
  return `MemberElement<${typed}, ${shape.properties.map(jsString).join(' | ')}>`
}

/**
 * A member's or part's definition module: its definition as data, its element
 * defined over the Solid member, and its tag in `HTMLElementTagNameMap`. A
 * member with a date or a time prop imports the temporal codecs
 * (`@polymorph/elements/temporal`) and gives them to `define`.
 */
export function renderElementsDefinition(
  shell: MemberShell,
  shape: ElementShape,
  options: { part?: string } = {},
): string {
  const { definition } = shape
  const name = shape.component
  const foundation = (shell.home ?? 'vocabulary') === 'foundation'
  const elementName = `Poly${name}`
  const props = `${name}Props`
  const source = descriptionPath(shell)
  const what =
    options.part === undefined ? `the ${shell.member} member` : `${shell.member}.${options.part}`
  const lines = [
    '/**',
    ` * \`<${definition.tag}>\`, ${what} as a custom element: the Solid ${options.part === undefined ? 'member' : 'part'}`,
    ` * (\`@polymorph/solid${foundation ? '' : '-ui'}\`) rendered into the element, in the light DOM.`,
    ' *',
    ` * ${MARKER} from \`${source}\`. Never edit it by hand.`,
    ' */',
  ]
  // An element with no props takes no props type.
  const typed = shape.properties.length > 0
  const member = typed ? `${shell.member}, type ${props}` : shell.member
  const element = typed ? 'MemberElement' : 'PolyElement'
  // A member with a date or a time prop brings the temporal codecs, and with them the date library,
  // which the bridge every element shares does not import.
  const temporal = Object.values(definition.props).some(
    (codec) => typeof codec === 'object' && 'temporal' in codec,
  )
  if (foundation) {
    lines.push(
      `import { ${member} } from '@polymorph/solid'`,
      '',
      `import { define, type ${element} } from '../element'`,
      `import type { ElementDefinition } from '../definition'`,
      ...(temporal ? ["import { temporal } from '../temporal'"] : []),
    )
  } else {
    // The Solid member's own module, not the vocabulary's index: the index attaches every compound's
    // parts, so a page that loads one element through it would load every compound member too.
    const file = `@polymorph/solid-ui/${shell.dir}/${name}`
    lines.push(
      `import { define, type ElementDefinition, type ${element} } from '@polymorph/elements'`,
      ...(temporal ? ["import { temporal } from '@polymorph/elements/temporal'"] : []),
      typed ? `import ${name}, { type ${props} } from '${file}'` : `import ${name} from '${file}'`,
    )
  }
  const component = foundation ? shell.member : name
  lines.push(
    '',
    `/** How \`<${definition.tag}>\` reads its attributes, dispatches its events and fills its slots. */`,
    `export const definition: ElementDefinition = ${definitionLiteral(definition)}`,
    '',
    `/** The \`<${definition.tag}>\` element. */`,
    `export type ${elementName}Element = ${elementType(shape, props, shell.generic)}`,
    '',
    `export const ${elementName} = define(definition, ${component}${temporal ? ', temporal' : ''})`,
    '',
    'declare global {',
    '  interface HTMLElementTagNameMap {',
    `    '${definition.tag}': ${elementName}Element`,
    '  }',
    '}',
    '',
  )
  return lines.join('\n')
}

