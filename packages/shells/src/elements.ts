/** A named type a prop's type can reach: a declaration, or a member's props as the registry lists them. */
export type Declared = ts.TypeNode | ts.InterfaceDeclaration | readonly RegistryPropLike[]

/**
 * The types a prop's type names, by name: every description's `types`, every
 * member's props interface (`EmptyStateProps`) as the registry lists its
 * props, and the types the engine exports, which the foundations re-export
 * (`ChartMessages`, `ToastAction`).
 */
export type DataTypes = ReadonlyMap<string, Declared>

/** A type written as TypeScript, as a type node. */
export function typeNode(text: string): ts.TypeNode {
  const source = ts.createSourceFile('type.ts', `type T = ${text}`, ts.ScriptTarget.ESNext, true)
  const alias = source.statements[0]
  if (alias === undefined || !ts.isTypeAliasDeclaration(alias)) {
    throw new Error(`shells: "${text}" is not a type`)
  }
  return alias.type
}

/** Every type the engine exports from its sources, by name. */
function engineTypes(root: string, out: Map<string, Declared>): void {
  const visit = (dir: string) => {
    for (const name of readdirSync(dir).sort()) {
      const path = join(dir, name)
      if (statSync(path).isDirectory()) {
        visit(path)
        continue
      }
      if (!name.endsWith('.ts') || name.endsWith('.test.ts') || name.endsWith('.d.ts')) continue
      const source = ts.createSourceFile(
        path,
        readFileSync(path, 'utf8'),
        ts.ScriptTarget.ESNext,
        true,
      )
      for (const statement of source.statements) {
        const exported = ts
          .getModifiers(statement as ts.HasModifiers)
          ?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword)
        if (exported !== true) continue
        if (ts.isInterfaceDeclaration(statement)) out.set(statement.name.text, statement)
        else if (ts.isTypeAliasDeclaration(statement)) out.set(statement.name.text, statement.type)
      }
    }
  }
  visit(resolve(root, 'packages/engine/src'))
}

/** The types every prop's type can name: the descriptions', the members' props and the engine's. */
export function dataTypes(
  root: string,
  registry: Registry,
  shells: readonly MemberShell[],
): DataTypes {
  const types = new Map<string, Declared>()
  engineTypes(root, types)
  for (const component of registry.components) types.set(`${component.name}Props`, component.props)
  for (const shell of shells) {
    for (const [name, text] of Object.entries(shell.types ?? {})) {
      // A generic type writes its parameters first (`<Row> { … }`); the shape is the same for every argument.
      types.set(name, typeNode(text.replace(/^\s*<[^>]*>\s*/, '')))
    }
  }
  return types
}

/**
 * A callback the bridge completes in a prop's JSON value: on each object at
 * `at` that has none and whose literal fields hold one of the values `where`
 * names for them (a Menu's `onSelect` on an item, not on a checkbox entry).
 */
interface Callback {
  at: string
  name: string
  where?: { field: string; is: (string | null)[] }[]
}

/** What a prop's data holds besides data: functions, callbacks the bridge completes, and node fields. */
export interface DataShape {
  /** A function the value must hold, which no JSON writes and the bridge does not complete. */
  functions: boolean
  /** The required `on*` callbacks of the value's objects, which the bridge completes with an event. */
  callbacks: Callback[]
  /** The node fields of the value's own object, which dotted slots fill (`topbar.leading`). */
  nodes: string[]
}

const NODE_TYPES = /^(VNode|ReactNode|ReactElement|JSX\.Element)$/
const WRAPPERS = new Set(['Readonly', 'Partial', 'Required', 'NonNullable', 'Pick', 'Omit'])

/** A field of an object type: its name, its type and whether it may be left out. */
interface Field {
  name: string
  type: ts.TypeNode
  optional: boolean
  /** A method, which is a function whatever its type says. */
  method?: true
}

/**
 * What a prop's type holds besides data, read through the types it names. An
 * array's items are read at the array's own path; an object's fields one
 * step down (`entries.items` in a Menubar's menus). A required function field
 * named `onX` is a callback the bridge completes, on the objects whose
 * literal fields match its own type's (`kind: 'checkbox'`); any other
 * required function, or a value that is itself a function, makes the prop a
 * property only. A type that holds itself is read once, at its first path.
 */
export function dataShape(type: string, types: DataTypes): DataShape {
  const shape: DataShape = { functions: false, callbacks: [], nodes: [] }
  const seen = new Set<string>()
  const callbacks = new Map<string, Callback>()
  const nodes = new Set<string>()

  const isFunction = (node: ts.TypeNode): boolean => {
    if (ts.isParenthesizedTypeNode(node)) return isFunction(node.type)
    return ts.isFunctionTypeNode(node) || ts.isConstructorTypeNode(node)
  }
  const isNode = (node: ts.TypeNode): boolean => {
    if (ts.isParenthesizedTypeNode(node)) return isNode(node.type)
    if (ts.isUnionTypeNode(node)) return node.types.some(isNode)
    return ts.isTypeReferenceNode(node) && NODE_TYPES.test(node.typeName.getText())
  }
  /** A union's parts other than `undefined` and `null`, and whether it had either. */
  const parts = (node: ts.TypeNode): { parts: ts.TypeNode[]; optional: boolean } => {
    if (ts.isParenthesizedTypeNode(node)) return parts(node.type)
    if (!ts.isUnionTypeNode(node)) return { parts: [node], optional: false }
    const kept = node.types.filter(
      (part) =>
        part.kind !== ts.SyntaxKind.UndefinedKeyword &&
        !(ts.isLiteralTypeNode(part) && part.literal.kind === ts.SyntaxKind.NullKeyword),
    )
    return { parts: kept, optional: kept.length < node.types.length }
  }

  /** An object type's literal fields, each with the values it may hold: `null` for none. */
  const literals = (fields: readonly Field[]): { field: string; is: (string | null)[] }[] =>
    fields.flatMap((field) => {
      const read = parts(field.type)
      const values = read.parts.map((part) =>
        ts.isLiteralTypeNode(part) && ts.isStringLiteral(part.literal) ? part.literal.text : null,
      )
      if (field.method === true || values.length === 0 || values.includes(null)) return []
      const is: (string | null)[] = [...values]
      if (field.optional || read.optional) is.push(null)
      return [{ field: field.name, is }]
    })

  const object = (fields: readonly Field[], at: string, top: boolean) => {
    const where = literals(fields)
    for (const field of fields) {
      const read = parts(field.type)
      const fn = field.method === true || (read.parts.length > 0 && read.parts.every(isFunction))
      if (fn) {
        if (field.optional || read.optional) continue
        if (!/^on[A-Z]/.test(field.name)) {
          shape.functions = true
          continue
        }
        const callback: Callback = {
          at,
          name: field.name,
          ...(where.length > 0 ? { where } : {}),
        }
        callbacks.set(JSON.stringify(callback), callback)
        continue
      }
      if (isNode(field.type)) {
        if (top) nodes.add(field.name)
        continue
      }
      walk(field.type, at === '' ? field.name : `${at}.${field.name}`, false)
    }
  }

  /** The fields of a type literal or an interface's own body. */
  const fieldsOf = (list: readonly ts.TypeElement[]): Field[] =>
    list.flatMap((member): Field[] => {
      const name = member.name?.getText().replace(/^['"]|['"]$/g, '') ?? ''
      const optional = 'questionToken' in member && member.questionToken !== undefined
      if (ts.isMethodSignature(member)) {
        return [
          {
            name,
            type: member.type ?? ts.factory.createKeywordTypeNode(ts.SyntaxKind.UnknownKeyword),
            optional,
            method: true,
          },
        ]
      }
      if (ts.isPropertySignature(member) && member.type !== undefined) {
        return [{ name, type: member.type, optional }]
      }
      if (ts.isCallSignatureDeclaration(member)) shape.functions = true
      return []
    })

  const named = (name: string, at: string, top: boolean) => {
    const declared = types.get(name)
    if (declared === undefined || seen.has(name)) return
    seen.add(name)
    if (Array.isArray(declared)) {
      object(
        (declared as readonly RegistryPropLike[]).map((prop) => ({
          name: prop.name,
          type: typeNode(prop.type),
          optional: prop.optional,
        })),
        at,
        top,
      )
    } else if (ts.isInterfaceDeclaration(declared as ts.Node)) {
      const declaration = declared as ts.InterfaceDeclaration
      for (const clause of declaration.heritageClauses ?? []) {
        for (const base of clause.types) named(base.expression.getText(), at, top)
      }
      object(fieldsOf(declaration.members), at, top)
    } else {
      walk(declared as ts.TypeNode, at, top)
    }
    seen.delete(name)
  }

  const walk = (node: ts.TypeNode, at: string, top: boolean): void => {
    if (ts.isParenthesizedTypeNode(node) || ts.isTypeOperatorNode(node)) walk(node.type, at, top)
    else if (ts.isUnionTypeNode(node) || ts.isIntersectionTypeNode(node)) {
      for (const part of node.types) walk(part, at, top)
    } else if (isFunction(node)) shape.functions = true
    else if (ts.isArrayTypeNode(node)) walk(node.elementType, at, false)
    else if (ts.isTupleTypeNode(node)) {
      for (const element of node.elements) walk(element, at, false)
    } else if (ts.isTypeLiteralNode(node)) object(fieldsOf(node.members), at, top)
    else if (ts.isTypeReferenceNode(node)) {
      const name = node.typeName.getText()
      const args = node.typeArguments ?? []
      if (
        name === 'Array' ||
        name === 'ReadonlyArray' ||
        name === 'Set' ||
        name === 'ReadonlySet'
      ) {
        for (const arg of args) walk(arg, at, false)
      } else if (name === 'Record') {
        if (args[1] !== undefined) walk(args[1], at, false)
      } else if (WRAPPERS.has(name)) {
        if (args[0] !== undefined) walk(args[0], at, top)
      } else if (!NODE_TYPES.test(name)) named(name, at, top)
    }
  }

  walk(typeNode(type), '', true)
  shape.callbacks = [...callbacks.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([, callback]) => callback)
  shape.nodes = [...nodes].sort()
  return shape
}

