/** The vocabulary's entry: every element it ships, its foundation, and every member's prop types. */
export function renderElementsIndex(
  native: readonly MemberShell[],
  every: readonly MemberShell[],
): string {
  const lines = [
    '/**',
    ' * `@polymorph/elements-ui`, the vocabulary as custom elements.',
    ' *',
    ' * Importing it defines every element it ships: each member, and each public',
    ' * part, as a `poly-*` element that renders the generated Solid member into',
    ' * itself. It exports each element, what a page reaches the elements through',
    " * from the foundation, and every member's prop types, which are the Solid",
    " * members' (`@polymorph/solid-ui`).",
    ' *',
    ` * ${MARKER}. Never edit it by hand.`,
    ' */',
    '',
    "export { define, PolyElement, PolymorphEvent, restore, toast } from '@polymorph/elements'",
    `export type { ${['ComponentStates', 'ElementDefinition', 'StateEntry', ...foundationTypeExports('elements')].join(', ')} } from '@polymorph/elements'`,
    '',
  ]
  const sorted = [...native].sort((a, b) => a.member.localeCompare(b.member))
  for (const shell of sorted) {
    const names = [
      shell.member,
      ...(shell.parts ?? [])
        .filter((part) => part.public)
        .map((part) => `${shell.member}${part.name}`),
    ]
    for (const name of names) {
      const module =
        (shell.home ?? 'vocabulary') === 'foundation'
          ? '@polymorph/elements'
          : `./${shell.dir}/${name}`
      lines.push(`export { Poly${name} } from '${module}'`)
      lines.push(`export type { Poly${name}Element } from '${module}'`)
    }
  }
  lines.push('')
  // Every member's types, for every member, so a screen imports them from the vocabulary as a React screen does.
  const fromSolid: string[] = []
  const fromFoundation: string[] = []
  for (const shell of [...every].sort((a, b) => a.member.localeCompare(b.member))) {
    const types = [
      `${shell.member}Props`,
      ...Object.keys(shell.types ?? {}),
      ...(shell.parts ?? [])
        .filter((part) => part.public)
        .map((part) => `${shell.member}${part.name}Props`),
    ]
    if ((shell.home ?? 'vocabulary') === 'foundation') fromFoundation.push(...types)
    else fromSolid.push(...types)
  }
  if (fromFoundation.length > 0) {
    lines.push(`export type { ${fromFoundation.sort().join(', ')} } from '@polymorph/elements'`)
  }
  lines.push(`export type { ${fromSolid.sort().join(', ')} } from '@polymorph/solid-ui'`, '')
  return lines.join('\n')
}

/** The galleries: every native member's states fixture, in the order of the descriptions. */
export function renderElementsGalleries(shells: readonly MemberShell[]): string {
  const lines = [
    '/**',
    ' * Every states fixture in the elements vocabulary, for the laws. A separate',
    ' * module from the index, so a page never loads the fixtures.',
    ' *',
    ` * ${MARKER}. Never edit it by hand.`,
    ' */',
    "import type { ComponentStates } from '@polymorph/elements'",
    '',
  ]
  const names = shells.map((shell) => ({
    shell,
    binding: `${shell.member.charAt(0).toLowerCase()}${shell.member.slice(1)}States`,
  }))
  for (const { shell, binding } of names) {
    lines.push(
      `import { states as ${binding} } from './${shell.fixtureDir ?? shell.dir}/${fixtureName(shell)}.states'`,
    )
  }
  lines.push(
    '',
    `export const GALLERIES: readonly ComponentStates[] = [${names.map(({ binding }) => binding).join(', ')}]`,
    '',
  )
  return lines.join('\n')
}

/**
 * Every element's definition, by tag: the table a loader defines the tags
 * from before it loads any member, and code that follows every element reads.
 */
export function renderElementsDefinitions(shapes: ReadonlyMap<string, ElementShape>): string {
  const lines = [
    '/**',
    " * Every element the elements vocabulary ships, by tag: each one's definition, as",
    ' * its definition module holds it, in a table that reads no member.',
    ' *',
    ` * ${MARKER}. Never edit it by hand.`,
    ' */',
    "import type { ElementDefinition } from '@polymorph/elements/definition'",
    '',
    'export const DEFINITIONS: Readonly<Record<string, ElementDefinition>> = {',
  ]
  for (const shape of shapes.values()) {
    lines.push(`  '${shape.definition.tag}': ${definitionLiteral(shape.definition)},`)
  }
  lines.push('}', '')
  return lines.join('\n')
}

/**
 * Every element's module, by tag, as a function that loads it: the table a
 * page that defines every tag at once (`defineLazy`) loads each member's code
 * from, the first time one of its elements renders. `poly-icon`'s module is
 * the foundation's (`@polymorph/elements/icon`).
 */
export function renderElementsLoaders(
  native: readonly MemberShell[],
  shapes: ReadonlyMap<string, ElementShape>,
): string {
  const modules = new Map<string, string>()
  for (const shell of native) {
    const foundation = (shell.home ?? 'vocabulary') === 'foundation'
    modules.set(
      shell.member,
      foundation ? `@polymorph/elements/${shell.dir}` : `./${shell.dir}/${shell.member}`,
    )
    for (const part of (shell.parts ?? []).filter((candidate) => candidate.public)) {
      modules.set(`${shell.member}${part.name}`, `./${shell.dir}/${shell.member}${part.name}`)
    }
  }
  const lines = [
    '/**',
    ' * Every element the elements vocabulary ships, by tag: a function that loads the',
    ' * module defining it. A page that defines every tag at once (`defineLazy`) loads a',
    " * member's code from here the first time one of its elements renders.",
    ' *',
    ` * ${MARKER}. Never edit it by hand.`,
    ' */',
    '',
    'export const LOADERS: Readonly<Record<string, () => Promise<unknown>>> = {',
  ]
  for (const shape of shapes.values()) {
    const module = modules.get(shape.component)
    if (module === undefined) throw new Error(`shells: no module defines ${shape.definition.tag}`)
    lines.push(`  '${shape.definition.tag}': () => import('${module}'),`)
  }
  lines.push('}', '')
  return lines.join('\n')
}

/** How a structural part's root lays out, by its tag: what its element shows before it renders. */
const PART_DISPLAY: Readonly<Record<string, string>> = {
  thead: 'table-header-group',
  tbody: 'table-row-group',
  tfoot: 'table-footer-group',
  tr: 'table-row',
  th: 'table-cell',
  td: 'table-cell',
  li: 'list-item',
  dt: 'block',
  dd: 'block',
  option: 'block',
}

/** How a member that holds structural parts lays out before it renders, by its parts' tags. */
const holderDisplay = (tags: ReadonlySet<string>): string =>
  [...tags].some((tag) => tag.startsWith('t')) ? 'table' : 'block'

/**
 * The foundation's rules for elements that have not rendered: an element not
 * yet defined, or defined and waiting for its member's code. An element that
 * renders its member carries the custom state `poly-host`, so each rule
 * selects `:not(:state(poly-host))`. The content of an overlay's slots stays
 * hidden, because the member shows it only when the overlay opens; a
 * structural part lays out as the element that replaces it, and the member
 * that holds it as a table or a block. Nothing else is hidden, so the page's
 * text stays readable if the code never loads.
 */
export function renderElementsPending(
  native: readonly MemberShell[],
  shapes: ReadonlyMap<string, ElementShape>,
): string {
  const waiting = (tag: string) => `${tag}:not(:state(poly-host))`
  const hidden: string[] = []
  const display = new Map<string, string>()
  for (const shape of shapes.values()) {
    const { tag, overlays } = shape.definition
    for (const slot of overlays ?? []) {
      hidden.push(
        `${waiting(tag)} > ${slot === 'children' ? ':not([slot])' : `[slot='${slotOf(slot)}']`}`,
      )
    }
  }
  for (const shell of native) {
    const tags = new Set<string>()
    for (const part of (shell.parts ?? []).filter((candidate) => candidate.public)) {
      const tag = hostElement(part.template)?.element.tag
      if (typeof tag !== 'string' || !STRUCTURAL_TAGS.has(tag)) continue
      const shown = PART_DISPLAY[tag]
      if (shown === undefined) throw new Error(`shells: no display for a part rendered as <${tag}>`)
      display.set(tagOf(`${shell.member}${part.name}`), shown)
      tags.add(tag)
    }
    if (tags.size > 0) display.set(tagOf(shell.member), holderDisplay(tags))
  }
  const lines = [
    '/* The rules for `poly-*` elements that have not rendered their member.',
    ' *',
    " * An element is not defined yet, or is defined and waits for its member's",
    ' * code. An element that renders carries the custom state `poly-host`, so',
    " * each rule matches only before then. An overlay's content stays hidden",
    " * until the overlay opens it; a table's and a list's parts lay out as the",
    ' * elements that replace them. Nothing else is hidden, so the text a page',
    " * wrote stays readable if the members' code never loads.",
    ' *',
    ` * ${MARKER}. Never edit it by hand. */`,
    '',
  ]
  if (hidden.length > 0) lines.push(`${hidden.sort().join(',\n')} {`, '  display: none;', '}', '')
  for (const [tag, shown] of [...display].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`${waiting(tag)} {`, `  display: ${shown};`, '}', '')
  }
  return lines.join('\n')
}

/**
 * Every file the elements renderer writes, unformatted, by repository path:
 * for each member the map marks native, its definition module and each public
 * part's, and its states fixture; the index, the galleries and the
 * definitions table.
 */
export function renderElementsFiles(
  root: string,
  registry: Registry,
  shells: readonly MemberShell[],
): Map<string, string> {
  const native = elementsMembers(root, shells)
  const shapes = elementShapes(registry, native, dataTypes(root, registry, shells))
  const files = new Map<string, string>()
  for (const shell of native) {
    files.set(
      elementsComponentPath(shell),
      renderElementsDefinition(shell, shapes.get(shell.member) as ElementShape),
    )
    for (const part of (shell.parts ?? []).filter((candidate) => candidate.public)) {
      files.set(
        elementsPartPath(shell, part.name),
        renderElementsDefinition(shell, shapes.get(`${shell.member}${part.name}`) as ElementShape, {
          part: part.name,
        }),
      )
    }
    if (!isPrimitive(registry, shell.member)) {
      files.set(
        elementsStatesPath(shell),
        renderElementsStates(shell, registryMember(registry, shell.member), shapes, native),
      )
    }
  }
  files.set(`${ELEMENTS_VOCABULARY_SRC}/index.ts`, renderElementsIndex(native, shells))
  files.set(
    `${ELEMENTS_VOCABULARY_SRC}/galleries.ts`,
    renderElementsGalleries(native.filter((shell) => !isPrimitive(registry, shell.member))),
  )
  files.set(`${ELEMENTS_VOCABULARY_SRC}/definitions.ts`, renderElementsDefinitions(shapes))
  files.set(`${ELEMENTS_VOCABULARY_SRC}/loaders.ts`, renderElementsLoaders(native, shapes))
  files.set(`${ELEMENTS_FOUNDATION_SRC}/pending.css`, renderElementsPending(native, shapes))
  return files
}
