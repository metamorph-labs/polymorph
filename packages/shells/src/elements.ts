/** Elements HTML writes without a closing tag. */
const VOID = new Set(['area', 'br', 'col', 'embed', 'hr', 'img', 'input', 'source', 'track', 'wbr'])

const escapeText = (text: string) =>
  text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
const escapeAttribute = (text: string) => text.replace(/&/g, '&amp;').replace(/"/g, '&quot;')
const escapeJsonAttribute = (text: string) => text.replace(/&/g, '&amp;').replace(/'/g, '&#39;')

/** What one entry's markup and script are being written with. */
interface Writing {
  shell: MemberShell
  shapes: ReadonlyMap<string, ElementShape>
  /** Elements of each tag written so far outside a template, for `find`. */
  counts: Map<string, number>
  /** The script's statements, in the order the markup needs them. */
  statements: string[]
  /** Each element the script names, by tag and index, with its variable. */
  variables: Map<string, string>
  /** Expressions the markup interpolates (a recipe's class), by their marker's index. */
  interpolated: string[]
  /** Inside a `<template>`, where an element is out of the document and `find` cannot reach it. */
  template: number
  /** What the file imports for this entry. */
  needs: Needs
}

interface Needs {
  recipes: Set<string>
  values: Set<string>
  helpers: Set<string>
  /** The components whose definition modules the fixture imports, so its elements are defined. */
  components: Set<string>
  /** The JavaScript the entries write that reads `zag`, the member's machine module. */
  zag: string[]
}

const indent = (depth: number) => '  '.repeat(depth)

/** A marker in the markup for an expression the template literal interpolates. */
function interpolate(expr: string, w: Writing): string {
  w.interpolated.push(expr)
  return `\uE000${w.interpolated.length - 1}\uE001`
}

/** The variable that names the `index`th element of `tag` in the script. */
function variable(tag: string, index: number, w: Writing): string {
  const id = `${tag}#${index}`
  const known = w.variables.get(id)
  if (known !== undefined) return known
  const name = `e${w.variables.size}`
  w.variables.set(id, name)
  w.statements.push(`const ${name} = find('${tag}', ${index})`)
  return name
}

/** A fixture value as JavaScript, for the script. */
function literal(value: FixtureValue, w: Writing): string {
  if (branded(value, 'js')) {
    const source = (value as { js: string }).js
    if (/(^|[^.\w$])zag\./.test(source)) w.needs.zag.push(source)
    for (const name of FIXTURE_VALUES) {
      if (new RegExp(`(^|[^.\\w$])${name}\\b`).test(source)) w.needs.values.add(name)
    }
    return source
  }
  if (branded(value, 'node')) return nodeCode((value as { node: FixtureChild }).node, w)
  if (branded(value, 'renders', RENDERS_KEYS)) {
    const { params, renders, when } = value as FixtureRenders
    const children = renderedChildren(renders).map((child) => nodeCode(child, w))
    const drawn = children.length === 1 ? children[0] : `[${children.join(', ')}]`
    return `(${params.join(', ')}) => ${when === undefined ? drawn : `(${when}) ? ${drawn} : undefined`}`
  }
  if (branded(value, 'held') || branded(value, 'hold', ['to'])) {
    throw new Error(`shells: ${w.shell.member}'s fixture holds a value inside another value`)
  }
  if (Array.isArray(value)) return `[${value.map((entry) => literal(entry, w)).join(', ')}]`
  if (value !== null && typeof value === 'object') {
    return `{ ${Object.entries(value as Record<string, FixtureValue>)
      .map(([name, entry]) => `${key(name)}: ${literal(entry, w)}`)
      .join(', ')} }`
  }
  return typeof value === 'string' ? jsString(value) : JSON.stringify(value)
}

/**
 * A node a fixture passes inside a value (a DescriptionList detail, a
 * DataTable cell), as the script creates it: a member's element with its props
 * set through its properties, or a plain element with its attributes, and its
 * children appended (`create`, `@polymorph/elements`). A member created there
 * renders on its own once its member puts it in the document.
 */
function nodeCode(child: FixtureChild, w: Writing, slot?: string): string {
  if (typeof child === 'string') return jsString(child)
  if ('js' in child) return literal(child, w)
  w.needs.helpers.add('create')
  const children = (list: readonly FixtureChild[]) =>
    `[${list.map((entry) => nodeCode(entry, w)).join(', ')}]`
  const fields: string[] = slot === undefined ? [] : [`slot: ${jsString(slot)}`]
  if ('member' in child) {
    const shape = w.shapes.get(child.member)
    if (shape === undefined) {
      throw new Error(
        `shells: ${w.shell.member}'s fixture writes ${child.member}, which the elements vocabulary does not ship — mark it native in ${ELEMENTS_MAP}`,
      )
    }
    w.needs.components.add(child.member)
    for (const [prop, value] of Object.entries(child.props ?? {})) {
      if (value === undefined) continue
      fields.push(`${key(prop)}: ${literal(value, w)}`)
    }
    for (const prop of shape.required) {
      if (prop in (child.props ?? {}) || shape.definition.events[prop]?.listened !== true) continue
      fields.push(`${prop}: () => {}`)
    }
    const nodes: string[] = []
    for (const [name, content] of Object.entries(child.slots ?? {})) {
      if (name === 'default') {
        nodes.push(...content.map((entry) => nodeCode(entry, w)))
        continue
      }
      const named = slotOf(name)
      if (content.every((entry) => typeof entry === 'object' && !('js' in entry))) {
        nodes.push(...content.map((entry) => nodeCode(entry, w, named)))
      } else {
        nodes.push(`create('template', { slot: ${jsString(named)} }, ${children(content)})`)
      }
    }
    return `create(${jsString(shape.definition.tag)}, { ${fields.join(', ')} }, [${nodes.join(', ')}])`
  }
  if (child.class !== undefined && child.class.length > 0) {
    const classes = child.class.map((name) => {
      w.needs.recipes.add(name.includes('.') ? (name.split('.')[0] as string) : 'styles')
      return classReference(name)
    })
    fields.push(`class: ${classes.length === 1 ? classes[0] : `[${classes.join(', ')}].join(' ')`}`)
  }
  for (const [name, value] of Object.entries(child.attrs ?? {})) {
    fields.push(`${key(name)}: ${jsString(value)}`)
  }
  return `create(${jsString(child.element)}, { ${fields.join(', ')} }, ${children(child.children ?? [])})`
}

/** Whether a fixture value is data JSON writes, with no JavaScript, node or held value inside. */
function plainData(value: FixtureValue): boolean {
  if (value === null || ['string', 'number', 'boolean'].includes(typeof value)) {
    return typeof value !== 'number' || Number.isFinite(value)
  }
  if (Array.isArray(value)) return value.every(plainData)
  if (typeof value !== 'object') return false
  if (['js', 'node', 'renders', 'held', 'hold'].some((brand) => brand in value)) return false
  return Object.values(value as Record<string, FixtureValue>).every(plainData)
}

/** A plain value as its attribute's text, or `null` when it has none (`null`, `undefined`). */
function attributeText(value: FixtureValue): string | null {
  if (value === null || value === undefined) return null
  if (value === true) return ''
  if (value === false) return 'false'
  if (typeof value === 'string') return value
  if (typeof value === 'number') return String(value)
  return JSON.stringify(value)
}

const pad = (value: string, width = 2) => value.trim().padStart(width, '0')

/**
 * A date or a time a fixture makes with JavaScript, as its ISO 8601 text, for
 * an element whose prop reads one: `new CalendarDate(2026, 7, 15)` and
 * `zag.parse('2026-07-15')` are `2026-07-15`, `new Time(9, 0)` is `09:00`,
 * and a range of two dates is `2026-06-01/2026-06-14`. `null` for anything else.
 */
function temporalText(value: FixtureValue, codec: Codec): string | null {
  if (typeof codec !== 'object' || !('temporal' in codec)) return null
  const one = (part: FixtureValue): string | null => {
    if (!branded(part, 'js')) return null
    const source = (part as { js: string }).js.trim()
    const parsed = /^zag\.parse\('([^']*)'\)( as zag\.\w+)?$/.exec(source)
    if (parsed !== null) return parsed[1] ?? null
    const made = /^new (Time|CalendarDate|CalendarDateTime)\(([\d,\s]*)\)$/.exec(source)
    if (made === null) return null
    const numbers = (made[2] ?? '').split(',').map((number) => number.trim())
    if (made[1] === 'Time') {
      const [hour = '0', minute = '0', second] = numbers
      return [pad(hour), pad(minute), ...(second === undefined ? [] : [pad(second)])].join(':')
    }
    const [year = '', month = '', day = '', hour, minute, second] = numbers
    const date = `${pad(year, 4)}-${pad(month)}-${pad(day)}`
    if (made[1] === 'CalendarDate') return date
    return `${date}T${[pad(hour ?? '0'), pad(minute ?? '0'), ...(second === undefined ? [] : [pad(second)])].join(':')}`
  }
  let text: string | null
  if (codec.temporal === 'range') {
    if (value === null || typeof value !== 'object' || Array.isArray(value)) return null
    const { start, end, ...rest } = value as Record<string, FixtureValue>
    if (Object.keys(rest).length > 0 || start === undefined || end === undefined) return null
    const from = one(start)
    const to = one(end)
    text = from === null || to === null ? null : `${from}/${to}`
  } else text = one(value)
  if (text === null) return null
  try {
    decode(codec, text)
    return text
  } catch {
    return null
  }
}

/** Whether the element reads an attribute's text back as the value the fixture gave. */
function readsBack(codec: Codec, text: string, value: FixtureValue): boolean {
  if (codec === 'property') return false
  try {
    return JSON.stringify(decode(codec, text)) === JSON.stringify(value)
  } catch {
    return false
  }
}

/** A member's element and what it holds, as markup, with its props the markup cannot hold in the script. */
function writeMember(
  component: string,
  props: Readonly<Record<string, FixtureValue>> | undefined,
  slots: Readonly<Record<string, readonly FixtureChild[]>> | undefined,
  depth: number,
  w: Writing,
  options: { slot?: string; children?: (depth: number) => string[]; textual?: boolean } = {},
): string {
  const shape = w.shapes.get(component)
  if (shape === undefined) {
    throw new Error(
      `shells: ${w.shell.member}'s fixture writes ${component}, which the elements vocabulary does not ship — mark it native in ${ELEMENTS_MAP}`,
    )
  }
  const { definition } = shape
  const tag = definition.tag
  const index = w.counts.get(tag) ?? 0
  if (w.template === 0) w.counts.set(tag, index + 1)
  w.needs.components.add(component)
  const element = () => {
    if (w.template > 0) {
      throw new Error(
        `shells: ${w.shell.member}'s fixture sets a property of ${component} inside a template`,
      )
    }
    return variable(tag, index, w)
  }
  const attributes: string[] = options.slot === undefined ? [] : [`slot="${options.slot}"`]
  /** Node fields of an object prop, which children with a dotted slot name fill. */
  const dotted: [string, FixtureChild][] = []
  for (const [prop, given] of Object.entries(props ?? {})) {
    let value = given
    if (value === undefined) continue
    const fields = definition.fields?.[prop]
    if (
      fields !== undefined &&
      value !== null &&
      typeof value === 'object' &&
      !Array.isArray(value)
    ) {
      const rest: Record<string, FixtureValue> = {}
      for (const [field, inner] of Object.entries(value as Record<string, FixtureValue>)) {
        if (fields.includes(field) && branded(inner, 'node')) {
          dotted.push([`${slotOf(prop)}.${slotOf(field)}`, (inner as { node: FixtureChild }).node])
        } else rest[field] = inner
      }
      if (Object.keys(rest).length === 0) continue
      value = rest
    }
    if (prop in definition.events) {
      const type = (definition.events[prop] as ElementEvent).type
      if (branded(value, 'js')) {
        w.needs.helpers.add('listen')
        w.statements.push(`listen(${element()}, '${type}', ${literal(value, w)})`)
      } else if (branded(value, 'hold', ['to'])) {
        const { hold, to } = value as { hold: string; to?: FixtureValue }
        w.needs.helpers.add('listen')
        w.statements.push(
          'to' in value
            ? `listen(${element()}, '${type}', () => held.set('${hold}', ${literal(to, w)}))`
            : `listen(${element()}, '${type}', (value) => held.set('${hold}', value))`,
        )
      } else {
        throw new Error(
          `shells: ${w.shell.member}'s fixture gives ${component}.${prop} no function`,
        )
      }
      continue
    }
    const codec = definition.props[prop]
    if (codec === undefined) {
      throw new Error(
        `shells: ${w.shell.member}'s fixture sets ${component}.${prop}, which is not a value prop of its element`,
      )
    }
    const temporal = temporalText(value, codec)
    if (temporal !== null) {
      attributes.push(`${attributeOf(prop)}="${escapeAttribute(temporal)}"`)
      continue
    }
    if (plainData(value)) {
      const text = attributeText(value)
      if (text !== null && readsBack(codec, text, value)) {
        const name = attributeOf(prop)
        attributes.push(
          text === ''
            ? name
            : typeof value === 'object'
              ? `${name}='${escapeJsonAttribute(text)}'`
              : `${name}="${escapeAttribute(text)}"`,
        )
        continue
      }
    }
    if (!shape.properties.includes(prop)) {
      // A prop with no property is set by its attribute alone. `null` is written as no
      // attribute, which the member reads as the prop left out.
      if (value === null) continue
      throw new Error(
        `shells: ${w.shell.member}'s fixture gives ${component}.${prop} a value its attribute cannot hold, and the prop has no property, because its name is a method every element inherits`,
      )
    }
    const property = propertyOf(prop)
    const target = isIdentifier(property) ? `.${property}` : `[${jsString(property)}]`
    if (branded(value, 'held')) {
      w.needs.helpers.add('holding')
      w.statements.push(
        `held.bind('${(value as { held: string }).held}', ${element()}, '${property}')`,
      )
    } else {
      w.statements.push(`${element()}${target} = ${literal(value, w)}`)
    }
  }
  // A callback the member requires and the entry leaves out: a listener, where the member asks for one.
  for (const prop of shape.required) {
    if (prop in (props ?? {}) || definition.events[prop]?.listened !== true) continue
    w.needs.helpers.add('listen')
    w.statements.push(`listen(${element()}, '${definition.events[prop]?.type}', () => {})`)
  }
  const open = attributes.length === 0 ? `<${tag}` : `<${tag} ${attributes.join(' ')}`
  const parts: string[] = []
  let textual = options.textual === true
  for (const [name, content] of Object.entries(slots ?? {})) {
    const prop = name === 'default' ? 'children' : name
    if (!definition.slots.includes(prop)) {
      throw new Error(
        `shells: ${w.shell.member}'s fixture fills ${component}'s ${name}, which is not one of its slots`,
      )
    }
    if (name === 'default') {
      textual ||= content.some((child) => typeof child === 'string' || 'js' in child)
      parts.push(...content.map((child) => writeChild(child, depth + 1, w)))
      continue
    }
    const slot = slotOf(prop)
    if (content.every((child) => typeof child === 'object' && !('js' in child))) {
      parts.push(...content.map((child) => writeChild(child, depth + 1, w, slot)))
    } else {
      w.template += 1
      const inner = content.map((child) => writeChild(child, depth + 2, w)).join('')
      w.template -= 1
      parts.push(`<template slot="${slot}">${inner}</template>`)
    }
  }
  for (const [slot, child] of dotted) {
    if (typeof child === 'object' && !('js' in child))
      parts.push(writeChild(child, depth + 1, w, slot))
    else {
      w.template += 1
      const inner = writeChild(child, depth + 2, w)
      w.template -= 1
      parts.push(`<template slot="${slot}">${inner}</template>`)
    }
  }
  if (options.children !== undefined) parts.push(...options.children(depth + 1))
  const body =
    parts.length === 0
      ? ''
      : textual
        ? parts.join('')
        : `${parts.map((part) => `\n${indent(depth + 1)}${part}`).join('')}\n${indent(depth)}`
  return `${open}>${body}</${tag}>`
}

/** A plain element and what it holds, written on one line, as JSX writes no whitespace between its nodes. */
function writeElement(
  child: { element: string; attrs?: Readonly<Record<string, string>>; class?: readonly string[] },
  children: readonly FixtureChild[],
  depth: number,
  w: Writing,
  options: { slot?: string; children?: (depth: number) => string[] } = {},
): string {
  const attributes: string[] = options.slot === undefined ? [] : [`slot="${options.slot}"`]
  if (child.class !== undefined && child.class.length > 0) {
    const classes = child.class.map((name) => {
      w.needs.recipes.add(name.includes('.') ? (name.split('.')[0] as string) : 'styles')
      return interpolate(classReference(name), w)
    })
    attributes.push(`class="${classes.join(' ')}"`)
  }
  for (const [name, value] of Object.entries(child.attrs ?? {})) {
    attributes.push(`${name}="${escapeAttribute(value)}"`)
  }
  const open =
    attributes.length === 0 ? `<${child.element}` : `<${child.element} ${attributes.join(' ')}`
  if (VOID.has(child.element)) return `${open}>`
  // No whitespace between a plain element's nodes: nothing drops it from the page's own elements.
  const inner = children.map((entry) => writeChild(entry, depth + 1, w)).join('')
  const outer = options.children === undefined ? [] : options.children(depth + 1)
  return `${open}>${inner}${outer.join('')}</${child.element}>`
}

/** Slot content as markup: text, a member's element, or a plain element. */
function writeChild(child: FixtureChild, depth: number, w: Writing, slot?: string): string {
  if (typeof child === 'string') return escapeText(child)
  if ('js' in child) {
    throw new Error(
      `shells: ${w.shell.member}'s fixture computes slot text with an expression, which the elements renderer does not write`,
    )
  }
  if ('member' in child) {
    return writeMember(
      child.member,
      child.props,
      child.slots,
      depth,
      w,
      slot === undefined ? {} : { slot },
    )
  }
  return writeElement(child, child.children ?? [], depth, w, slot === undefined ? {} : { slot })
}

/** The markup a template literal holds, with each interpolated expression in place of its marker. */
function templateLiteral(html: string, interpolated: readonly string[]): string {
  const escaped = html.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')
  return `\`${escaped.replace(/\uE000(\d+)\uE001/g, (_, at: string) => `\${${interpolated[Number(at)]}}`)}\``
}

function entryCode(
  shell: MemberShell,
  entry: StateEntry,
  shapes: ReadonlyMap<string, ElementShape>,
  needs: Needs,
): string {
  const w: Writing = {
    shell,
    shapes,
    counts: new Map(),
    statements: [],
    variables: new Map(),
    interpolated: [],
    template: 0,
    needs,
  }
  const component = entrySubject(shell, entry)
  const subject = shapes.get(component)?.definition.tag ?? tagOf(component)
  // The runner's overrides reach the first element of the subject's tag, so nothing before it has that tag.
  const before = (depth: number) => {
    const written = (entry.before ?? []).map((child) => writeChild(child, depth, w))
    if ((w.counts.get(subject) ?? 0) > 0) {
      throw new Error(
        `shells: ${shell.member}'s "${entry.name}" writes ${subject} before its subject`,
      )
    }
    return written
  }
  const instance = (instanceOf: FixtureInstance, depth: number) =>
    writeMember(component, instanceOf.props, instanceOf.slots, depth, w)
  let html: string
  if (entry.many !== undefined) {
    const many = entry.many
    const content = (depth: number) => [
      ...before(depth),
      ...many.each.map((each) => instance(each, depth)),
      ...(many.also ?? []).map((child) => writeChild(child, depth, w)),
    ]
    const within = many.within
    const textual = [...(entry.before ?? []), ...(many.also ?? [])].some(
      (child) => typeof child === 'string' || 'js' in child,
    )
    html =
      'element' in within
        ? writeElement(within, [], 0, w, { children: content })
        : writeMember(within.member, within.props, undefined, 0, w, { children: content, textual })
  } else {
    html = [...before(0), writeMember(component, entry.props, entry.slots, 0, w)].join('\n')
  }
  if (entry.holds !== undefined) {
    w.needs.helpers.add('holding')
    w.statements.unshift(`const held = holding(${literal(entry.holds, w)})`)
  } else if (w.statements.some((line) => /\bheld\./.test(line))) {
    throw new Error(`shells: ${shell.member}'s "${entry.name}" reads a held value it does not hold`)
  }
  const fields = [`name: ${jsString(entry.name)}`, `html: ${templateLiteral(html, w.interpolated)}`]
  if ((w.counts.get(subject) ?? 0) > 0) fields.push(`subject: '${subject}'`)
  if (w.statements.length > 0) fields.push(`setup: (find) => { ${w.statements.join('; ')} }`)
  if (entry.types !== undefined) {
    fields.push(
      `types: { into: ${jsString(entry.types.into)}, text: ${jsString(entry.types.text)} }`,
    )
  }
  if (entry.presses !== undefined) fields.push(`presses: ${jsString(entry.presses)}`)
  if (entry.selects !== undefined) {
    fields.push(
      `selects: { in: ${jsString(entry.selects.in)}, text: ${jsString(entry.selects.text)} }`,
    )
  }
  if (entry.expect) {
    fields.push(
      `expect: { ${Object.entries(entry.expect)
        .map(([name, value]) => `${key(name)}: ${value === null ? 'null' : jsString(value)}`)
        .join(', ')} }`,
    )
  }
  if (entry.rendersNothing) fields.push('rendersNothing: true')
  return `{ ${fields.join(', ')} }`
}

/** The module path, from a fixture's directory, of a component's definition module. */
function definitionModule(
  component: string,
  fromDir: string,
  locations: ReadonlyMap<string, { foundation: boolean; dir: string }>,
): string {
  const location = locations.get(component)
  if (location === undefined) throw new Error(`shells: ${component} has no definition module`)
  if (location.foundation) return '@polymorph/elements'
  return relativeFile(fromDir, location.dir, component)
}

/** Where each element's definition module is, by component name. */
function elementLocations(
  shells: readonly MemberShell[],
): Map<string, { foundation: boolean; dir: string }> {
  return new Map(
    shells.flatMap((shell) => [
      [
        shell.member,
        { foundation: (shell.home ?? 'vocabulary') === 'foundation', dir: shell.dir },
      ] as const,
      ...(shell.parts ?? [])
        .filter((part) => part.public)
        .map(
          (part) => [`${shell.member}${part.name}`, { foundation: false, dir: shell.dir }] as const,
        ),
    ]),
  )
}

/** A member's states fixture in element form: each entry's markup, and what its script sets. */
export function renderElementsStates(
  shell: MemberShell,
  component: RegistryMemberLike,
  shapes: ReadonlyMap<string, ElementShape>,
  shells: readonly MemberShell[],
): string {
  const needs: Needs = {
    recipes: new Set(),
    values: new Set(),
    helpers: new Set(),
    components: new Set(),
    zag: [],
  }
  const entries = [...gridEntries(shell, component), ...shell.states].map((entry) =>
    entryCode(shell, entry, shapes, needs),
  )
  const dir = shell.fixtureDir ?? shell.dir
  const lines = [
    '/**',
    ` * ${shell.member}'s states fixture in element form, with the React fixture's entry`,
    " * names, so a contract's `when <state>` names the same entry in every shell. Each",
    ' * entry is the markup a page writes, and what its script sets once the elements',
    ' * are defined.',
    ' *',
    ` * ${MARKER} from \`${descriptionPath(shell)}\`. Never edit it by hand.`,
    ' */',
  ]
  if (needs.zag.length > 0) {
    if (shell.machine === undefined) {
      throw new Error(`shells: ${shell.member}'s fixture reads \`zag\`, and it binds no machine`)
    }
    // A fixture whose JavaScript names the module's types only (a parameter's), and none of its
    // values, imports it as types: the dates it parses are written as their ISO text.
    const reads = needs.zag.some((source) =>
      /(^|[^.\w$])zag\./.test(source.replace(/(:\s*|\bas\s+)zag\.\w+/g, '')),
    )
    lines.push(`import ${reads ? '' : 'type '}* as zag from '@zag-js/${shell.machine.of}'`, '')
  }
  const values = [...new Set([...needs.helpers, ...needs.values])].sort()
  lines.push(
    values.length > 0
      ? `import { ${values.join(', ')}, type ComponentStates } from '@polymorph/elements'`
      : "import type { ComponentStates } from '@polymorph/elements'",
  )
  for (const binding of [...needs.recipes].sort()) {
    const recipe = binding === 'styles' ? shell.recipe : shell.recipes?.[binding]
    if (recipe === undefined || recipe === null) {
      throw new Error(
        `shells: ${shell.member}'s fixture names the recipe "${binding}", which it has not`,
      )
    }
    lines.push(`import ${binding} from '@polymorph/recipes/${recipe}.module.css'`)
  }
  lines.push('')
  const locations = elementLocations(shells)
  const modules = [
    ...new Set([...needs.components].map((name) => definitionModule(name, dir, locations))),
  ]
  // The elements the entries write, defined by their modules.
  for (const module of modules.filter((module) => module !== '@polymorph/elements').sort()) {
    lines.push(`import '${module}'`)
  }
  lines.push('')
  // The types the fixture's values name (DataTable's rows), declared once for every entry.
  for (const [name, type] of Object.entries(shell.fixtureTypes ?? {})) {
    lines.push(`type ${name} = ${type}`, '')
  }
  lines.push(
    'export const states: ComponentStates = {',
    `  component: '${shell.member}',`,
    `  entries: [${entries.join(', ')}],`,
    '}',
    '',
  )
  return lines.join('\n')
}

