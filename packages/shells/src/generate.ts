/**
 * `pnpm shells`: every file the descriptions generate, by repository path.
 *
 * Each framework is a target (`ShellTarget`): the trees its files live in and
 * a function that renders every file in them. For Vue: each member's
 * single-file component and states fixture, the vocabulary's index and
 * galleries, and the foundation's glyph data and Icon stylesheet. The registry
 * is built from source here, not read from `registry/`, so a changed React
 * prop reaches the shells without a separate `pnpm registry`.
 */

/** The marker every generated file carries, which `--check` and the cleanup read. */
export const GENERATED_MARKER = 'Generated by `pnpm shells`'

// The registry's reading of a described member, which every target and the laws use.
export { descriptionPath, isPrimitive, locations, registryMember, typeOwners } from './common'

export const VOCABULARY_SRC = 'packages/vue-ui/src'
export const FOUNDATION_SRC = 'packages/vue/src'

/** Where a member's compound part's component file goes. */
export function partPath(shell: MemberShell, part: string): string {
  return `${VOCABULARY_SRC}/${shell.dir}/${shell.member}${part}.vue`
}

/** Where a member's component file goes. */
export function componentPath(shell: MemberShell): string {
  const root = (shell.home ?? 'vocabulary') === 'foundation' ? FOUNDATION_SRC : VOCABULARY_SRC
  return `${root}/${shell.dir}/${shell.member}.vue`
}

export function statesPath(shell: MemberShell): string {
  return `${VOCABULARY_SRC}/${shell.fixtureDir ?? shell.dir}/${fixtureName(shell)}.states.ts`
}

const pascal = (kebab: string) =>
  kebab
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')

/**
 * The foundation's glyph data: each role's drawing, from the glyph
 * `design/icons.json` names for it (read through the engine's role data). The
 * React foundation imports the same glyphs by name in its map; the Vue
 * foundation ships them as data, so no icon library runs in a Vue application
 * either.
 */
export function renderGlyphs(): string {
  const glyphs = new Map<string, string>()
  for (const role of ICON_ROLES) {
    const glyph = ICON_ROLE_META[role].glyph
    const node = (lucide as unknown as Record<string, unknown>)[pascal(glyph)]
    if (!Array.isArray(node)) throw new Error(`shells: lucide has no glyph "${glyph}" for ${role}`)
    glyphs.set(glyph, JSON.stringify(node))
  }
  const constant = (glyph: string) => glyph.toUpperCase().replace(/-/g, '_').replace(/^(\d)/, '_$1')
  const lines = [
    '/**',
    " * Every icon role's drawing: the SVG elements of the glyph `design/icons.json` names",
    ' * for it, each as a tag and its attributes. `Glyph` draws them.',
    ' *',
    ` * ${GENERATED_MARKER} from the icon roles and the ${'`lucide`'} glyph data they name.`,
    ' * Never edit it by hand: remap a role in `design/icons.json` and run `pnpm shells`.',
    ' */',
    "import type { IconRole } from '@polymorph/engine'",
    '',
    '/** One glyph: the SVG elements that draw it. */',
    'export type GlyphDrawing = readonly (readonly [tag: string, attributes: Readonly<Record<string, string | number>>])[]',
    '',
  ]
  for (const [glyph, data] of [...glyphs].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`const ${constant(glyph)}: GlyphDrawing = ${data}`)
  }
  lines.push('')
  lines.push('export const GLYPHS: Readonly<Record<IconRole, GlyphDrawing>> = {')
  for (const role of ICON_ROLES) {
    lines.push(`  '${role}': ${constant(ICON_ROLE_META[role].glyph)},`)
  }
  lines.push('}')
  lines.push('')
  return lines.join('\n')
}

/** The React foundation's Icon stylesheet, the one both foundations' Icon draws with. */
export const ICON_STYLESHEET = 'packages/react/src/icon/icon.module.css'

/**
 * The Vue foundation's Icon stylesheet: the React foundation's, written beside
 * the Vue `Icon` under a header that says where it comes from. A foundation
 * cannot import a stylesheet from another package without depending on it, so
 * the file is copied, and `pnpm shells` writes the copy, so the two cannot
 * differ.
 */
export function renderIconStylesheet(root: string): string {
  const header = [
    "/* The Icon stylesheet, the React foundation's (`" + ICON_STYLESHEET + '`).',
    ` * ${GENERATED_MARKER} from it. Never edit it by hand: change that file and`,
    ' * run `pnpm shells`. */',
    '',
  ]
  return `${header.join('\n')}\n${readFileSync(resolve(root, ICON_STYLESHEET), 'utf8')}`
}

async function format(root: string, path: string, text: string): Promise<string> {
  const file = resolve(root, path)
  const config = (await prettier.resolveConfig(file)) ?? {}
  return prettier.format(text, { ...config, filepath: file })
}

/** Every description, in the registry's order. */
export async function describedMembers(registry: Registry): Promise<MemberShell[]> {
  return orderMembers(
    await loadMembers(),
    registry.components.map((component) => component.name),
  )
}

/**
 * A framework the descriptions render into. `render` returns every file the
 * target generates, unformatted, by repository path; every path is under one
 * of its `trees`, which the orphan walk reads. `format` formats one of its
 * files, and Prettier by the file's path does when it is absent.
 */
export interface ShellTarget {
  /** The name `pnpm shells --target` takes. */
  readonly name: string
  readonly trees: readonly string[]
  render(root: string, registry: Registry, shells: readonly MemberShell[]): Map<string, string>
  format?(root: string, path: string, text: string): Promise<string>
}

/** Every file the Vue renderer writes, unformatted. */
function renderVueFiles(
  root: string,
  registry: Registry,
  shells: readonly MemberShell[],
): Map<string, string> {
  const where = locations(shells)
  const owners = typeOwners(shells)
  const files = new Map<string, string>()
  for (const shell of shells) {
    const component = registryMember(registry, shell.member)
    const context: VueContext = { locations: where, owners, source: descriptionPath(shell) }
    files.set(componentPath(shell), renderVueMember(shell, component, context))
    for (const part of shell.parts ?? []) {
      const rendered = partShell(shell, part, component)
      files.set(
        partPath(shell, part.name),
        renderVueMember(rendered.shell, rendered.component, context, shell.member),
      )
    }
    if (!isPrimitive(registry, shell.member)) {
      files.set(statesPath(shell), renderVueStates(shell, component, context))
    }
  }
  files.set(`${VOCABULARY_SRC}/index.ts`, renderVueIndex(shells))
  files.set(
    `${VOCABULARY_SRC}/galleries.ts`,
    renderVueGalleries(shells.filter((shell) => !isPrimitive(registry, shell.member))),
  )
  files.set(`${FOUNDATION_SRC}/icon/glyphs.ts`, renderGlyphs())
  files.set(`${FOUNDATION_SRC}/icon/icon.module.css`, renderIconStylesheet(root))
  return files
}

export const VUE_TARGET: ShellTarget = {
  name: 'vue',
  trees: [VOCABULARY_SRC, FOUNDATION_SRC],
  render: renderVueFiles,
}

export const SVELTE_TARGET: ShellTarget = {
  name: 'svelte',
  trees: [SVELTE_VOCABULARY_SRC, SVELTE_FOUNDATION_SRC],
  render: (root, registry, shells) =>
    renderSvelteFiles(registry, shells, {
      glyphs: renderGlyphs(),
      stylesheet: renderIconStylesheet(root),
    }),
  format: formatSvelteFile,
}

