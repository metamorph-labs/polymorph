/** Every target, in the order `pnpm shells` writes them. */
export const TARGETS: readonly ShellTarget[] = [
  VUE_TARGET,
  SVELTE_TARGET,
  SOLID_TARGET,
  ANGULAR_TARGET,
  ELEMENTS_TARGET,
]

/** The target `pnpm shells --target <name>` names. */
export function targetNamed(name: string): ShellTarget {
  const target = TARGETS.find((candidate) => candidate.name === name)
  if (target === undefined) {
    throw new Error(
      `shells: no target called "${name}" — the targets are ${TARGETS.map((each) => each.name).join(', ')}`,
    )
  }
  return target
}

/** Every generated file of the targets, formatted, by repository path, in a fixed order. */
export async function generateShells(
  root: string,
  registry: Registry = buildRegistry(root),
  given?: readonly MemberShell[],
  targets: readonly ShellTarget[] = TARGETS,
): Promise<Map<string, string>> {
  const shells = given ?? (await describedMembers(registry))
  const formatted = new Map<string, string>()
  for (const target of targets) {
    for (const [path, text] of target.render(root, registry, shells)) {
      formatted.set(
        path,
        await (target.format ? target.format(root, path, text) : format(root, path, text)),
      )
    }
  }
  return formatted
}

/** Generated files on disk: every file under the targets' trees that carries the marker. */
export function generatedOnDisk(root: string, targets: readonly ShellTarget[] = TARGETS): string[] {
  const found: string[] = []
  const walk = (dir: string) => {
    if (!existsSync(dir)) return
    for (const name of readdirSync(dir)) {
      const path = join(dir, name)
      if (statSync(path).isDirectory()) {
        if (name !== 'node_modules' && name !== 'dist') walk(path)
        continue
      }
      if (!/\.(vue|svelte|ts|tsx|css)$/.test(name)) continue
      if (readFileSync(path, 'utf8').includes(GENERATED_MARKER)) found.push(relative(root, path))
    }
  }
  for (const target of targets) for (const tree of target.trees) walk(resolve(root, tree))
  return found.sort()
}

/** What differs between the generated files and the disk: stale, missing and orphaned paths. */
export function staleness(
  root: string,
  generated: ReadonlyMap<string, string>,
  targets: readonly ShellTarget[] = TARGETS,
): string[] {
  const faults: string[] = []
  for (const [path, text] of generated) {
    const file = resolve(root, path)
    if (!existsSync(file)) faults.push(`${path}: missing`)
    else if (readFileSync(file, 'utf8') !== text) faults.push(`${path}: stale`)
  }
  for (const path of generatedOnDisk(root, targets)) {
    if (!generated.has(path)) faults.push(`${path}: no description generates it`)
  }
  return faults
}
