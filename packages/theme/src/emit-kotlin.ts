import { emitTokenDocument } from './emit-tokens'
import {
  escapeNativeString,
  fixedNumber,
  nativeTheme,
  nativePairingNames,
  printNative,
  type NativeSyntax,
  type NativeValue,
} from './native-model'
import type { ResolvedTheme } from './theme'

/**
 * Kotlin sources for `platforms/android`: one file per pairing declaring its
 * `PMTheme`, and `Catalogue.kt` naming them all in `PMThemes`.
 *
 * The classes live in the hand-written `PMTheme.kt` in the same package; this
 * emitter writes values only. It reads the token document for `android`, so
 * the hit target is already at the 48dp floor (control heights are the
 * density's, as on the web; a member extends its hit area to the hit target
 * with `minimumInteractiveComponentSize`) and the page texture is listed in
 * `unsupported` rather than emitted. The values are plain
 * Kotlin (no Android or Compose import), so `kotlinc` alone compiles them and
 * the module is multiplatform-safe; the Compose mapping is one line per type
 * (`Color(rgba.argb)`, `radius.md.dp`, `text.md.size.sp`).
 *
 * Determinism: the same pairing gives the same bytes. Numbers are printed by
 * `fixedNumber` with at most four decimals; an alpha is printed exactly, and
 * one with more decimals throws.
 *
 * The classes take the shared model's names (`native-model.ts`) except where
 * `KOTLIN_TYPE_NAMES` renames one for Kotlin.
 */

export const KOTLIN_PACKAGE = 'dev.polymorph.tokens'

const KOTLIN: NativeSyntax = {
  indent: '    ',
  int: (value) => fixedNumber(value),
  float: (value, exact) => `${fixedNumber(value, { exact })}f`,
  string: (value) => `"${escapeNativeString(value, '"')}"`,
  bool: (value) => String(value),
  listOpen: 'listOf(',
  listClose: ')',
  argument: (name) => `${name} = `,
}

/**
 * Kotlin's names for the classes the shared model names otherwise. `PMIcon` is
 * the vocabulary member Icon in the member module (`dev.polymorph.ui`), and an
 * app imports both packages, so the icon sizes are `PMIconScale`, as in Swift.
 */
export const KOTLIN_TYPE_NAMES: Readonly<Record<string, string>> = { PMIcon: 'PMIconScale' }

/** The tree with every class Kotlin names otherwise renamed (`KOTLIN_TYPE_NAMES`). */
export function kotlinNames(value: NativeValue): NativeValue {
  if (value.kind === 'list') return { ...value, items: value.items.map(kotlinNames) }
  if (value.kind !== 'object') return value
  return {
    ...value,
    type: KOTLIN_TYPE_NAMES[value.type] ?? value.type,
    fields: value.fields.map(([name, inner]) => [name, kotlinNames(inner)]),
  }
}

const header = (from: string) =>
  [
    `// Generated by \`pnpm emit:native\` from ${from}. Never hand-edited: change the`,
    '// system or palette in design/ and run `pnpm emit:native` again.',
    '',
    `package ${KOTLIN_PACKAGE}`,
    '',
  ].join('\n')

/**
 * The Kotlin source for one pairing: an internal object holding its theme,
 * which `PMThemes` exposes. An object initialises on first use, so an app pays
 * only for the pairings it reads.
 */
export function emitKotlin(theme: ResolvedTheme): string {
  const [names] = nativePairingNames([theme])
  const tree = kotlinNames(nativeTheme(emitTokenDocument(theme, { platform: 'android' })))
  const lead = 'val theme: PMTheme = '
  return [
    header(`${theme.system}/${theme.palette}`),
    `internal object ${names!.type} {`,
    `${KOTLIN.indent}${lead}${printNative(tree, KOTLIN, 1, lead.length)}`,
    '}',
    '',
  ].join('\n')
}

export interface KotlinOptions {
  /**
   * The pairing `emitKotlinFiles` declares as `PMThemes.default`: the web's
   * default, `design/defaults.json`'s system with its default palette, which
   * the member module's `LocalPMTheme` starts from. Absent, the first pairing
   * is the default.
   */
  defaultPairing?: { system: string; palette: string }
}

/**
 * Every file for a set of pairings, by file name: `<Pairing>.kt` for each
 * (`Plain_Neutral.kt`) and `Catalogue.kt`, which declares `PMThemes` with one
 * property per pairing, `catalogue`, `default` (`KotlinOptions.defaultPairing`)
 * and `named(system, palette)`. With no pairings there is no default to name.
 */
export function emitKotlinFiles(
  themes: readonly ResolvedTheme[],
  options: KotlinOptions = {},
): Record<string, string> {
  const names = nativePairingNames(themes)
  const files: Record<string, string> = {}
  themes.forEach((theme, index) => {
    files[`${names[index]!.type}.kt`] = emitKotlin(theme)
  })
  const wanted = options.defaultPairing
  const chosen =
    wanted === undefined
      ? 0
      : themes.findIndex(
          (theme) => theme.system === wanted.system && theme.palette === wanted.palette,
        )
  if (wanted !== undefined && chosen === -1) {
    throw new Error(
      `emitKotlinFiles: the default pairing ${wanted.system}/${wanted.palette} is not among the pairings`,
    )
  }
  const i1 = KOTLIN.indent
  const i2 = i1.repeat(2)
  const defaultTheme =
    themes.length === 0
      ? []
      : [
          `${i1}/**`,
          `${i1} * The default pairing, ${themes[chosen]!.system}/${themes[chosen]!.palette}: the one a member renders under`,
          `${i1} * until the app provides another.`,
          `${i1} */`,
          `${i1}val default: PMTheme get() = ${names[chosen]!.member}`,
          '',
        ]
  const catalogue = [
    header('the catalogue'),
    '/** Every pairing this package carries: each house system with its default palette. */',
    'object PMThemes {',
    ...themes.flatMap((theme, index) => [
      `${i1}/** ${theme.system}/${theme.palette}. */`,
      `${i1}val ${names[index]!.member}: PMTheme get() = ${names[index]!.type}.theme`,
      '',
    ]),
    `${i1}/** Every pairing, in system order. Reading it initialises each one. */`,
    `${i1}val catalogue: List<PMTheme> get() = listOf(`,
    ...names.map((name) => `${i2}${name.member},`),
    `${i1})`,
    '',
    ...defaultTheme,
    `${i1}/** The pairing of \`system\` and \`palette\`, or null when this package does not carry it. */`,
    `${i1}fun named(system: String, palette: String): PMTheme? = when ("$system/$palette") {`,
    ...themes.map(
      (theme, index) =>
        `${i2}${KOTLIN.string(`${theme.system}/${theme.palette}`)} -> ${names[index]!.member}`,
    ),
    `${i2}else -> null`,
    `${i1}}`,
    '}',
    '',
  ]
  files['Catalogue.kt'] = catalogue.join('\n')
  return files
}
