import { emitTokenDocument } from './emit-tokens'
import {
  escapeNativeString,
  fixedNumber,
  nativeTheme,
  nativePairingNames,
  printNative,
  type NativeSyntax,
} from './native-model'
import type { ResolvedTheme } from './theme'

/**
 * Dart sources for `platforms/dart` (`polymorph_tokens`): one library per
 * pairing declaring its theme as a `const`, and `catalogue.dart` naming them
 * all in `PMThemes`.
 *
 * The classes live in the hand-written `lib/src/pm_theme.dart`, the classes
 * the Kotlin package declares, under the shared model's names: Kotlin renames
 * the icon sizes' `PMIcon` to `PMIconScale` (`KOTLIN_TYPE_NAMES`) and Dart does
 * not. This emitter writes values only. It
 * reads the token document for `dart`, whose hit-target floor is Flutter's
 * 48, so the hit target is already raised (control heights are the density's,
 * as on the web) and the page texture is listed in `unsupported` rather than
 * emitted. Nothing imports Flutter: a
 * Flutter app maps each value in one line (`Color(rgba.argb)`, a `double` for
 * every length).
 *
 * Determinism: the same pairing gives the same bytes. Numbers are printed by
 * `fixedNumber` with at most four decimals; an alpha is printed exactly, and
 * one with more decimals throws. A `double` always carries a decimal point.
 */

const DART: NativeSyntax = {
  indent: '  ',
  int: (value) => fixedNumber(value),
  float: (value, exact) => {
    const text = fixedNumber(value, { exact })
    return text.includes('.') ? text : `${text}.0`
  },
  string: (value) => `'${escapeNativeString(value, "'")}'`,
  bool: (value) => String(value),
  listOpen: '[',
  listClose: ']',
  argument: (name) => `${name}: `,
}

const header = (from: string) =>
  [
    `// Generated by \`pnpm emit:native\` from ${from}. Never hand-edited: change the`,
    '// system or palette in design/ and run `pnpm emit:native` again.',
    '',
  ].join('\n')

/** The Dart library for one pairing: `const PMTheme theme`. */
export function emitDart(theme: ResolvedTheme): string {
  const tree = nativeTheme(emitTokenDocument(theme, { platform: 'dart' }))
  const lead = 'const PMTheme theme = '
  return [
    header(`${theme.system}/${theme.palette}`),
    "import '../pm_theme.dart';",
    '',
    `/// ${theme.system}/${theme.palette}.`,
    `${lead}${printNative(tree, DART, 0, lead.length)};`,
    '',
  ].join('\n')
}

/**
 * Every file for a set of pairings, by file name: `<system>_<palette>.dart`
 * for each and `catalogue.dart`, which declares `PMThemes` with one constant
 * per pairing, `catalogue`, and `named(system, palette)`.
 */
export function emitDartFiles(themes: readonly ResolvedTheme[]): Record<string, string> {
  const names = nativePairingNames(themes)
  // An import prefix may not share a name with a member of the class that
  // reads it. A member has one underscore (`plain_neutral`); a prefix has two.
  const prefixes = names.map((name) => `${name.snake}_lib`)
  const files: Record<string, string> = {}
  themes.forEach((theme, index) => {
    files[`${names[index]!.snake}.dart`] = emitDart(theme)
  })
  const i1 = DART.indent
  const i2 = i1.repeat(2)
  const imports = themes
    .map((_, index) => `import '${names[index]!.snake}.dart' as ${prefixes[index]};`)
    .sort()
  const catalogue = [
    header('the catalogue'),
    "import '../pm_theme.dart';",
    ...imports,
    '',
    '/// Every pairing this package carries: each house system with its default palette.',
    'abstract final class PMThemes {',
    ...themes.flatMap((theme, index) => [
      `${i1}/// ${theme.system}/${theme.palette}.`,
      `${i1}static const PMTheme ${names[index]!.member} = ${prefixes[index]}.theme;`,
      '',
    ]),
    `${i1}/// Every pairing, in system order.`,
    `${i1}static const List<PMTheme> catalogue = [`,
    ...names.map((name) => `${i2}${name.member},`),
    `${i1}];`,
    '',
    `${i1}/// The pairing of [system] and [palette], or null when this package does not carry it.`,
    `${i1}static PMTheme? named(String system, String palette) => switch ('$system/$palette') {`,
    ...themes.map(
      (theme, index) =>
        `${i2}${DART.string(`${theme.system}/${theme.palette}`)} => ${names[index]!.member},`,
    ),
    `${i2}_ => null,`,
    `${i1}};`,
    '}',
    '',
  ]
  files['catalogue.dart'] = catalogue.join('\n')
  return files
}
