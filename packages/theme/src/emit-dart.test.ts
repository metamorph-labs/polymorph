/**
 * `dart analyze --fatal-infos` over a copy of the package with the probe's
 * output added, so the exception classes no catalogue pairing declares are
 * checked too. The copy keeps the package's own `analysis_options.yaml`, and
 * the package has no dependencies, so nothing is fetched. The freshness law
 * (`native.test.ts`) proves the files on disk are what the emitter writes; this
 * proves Dart accepts them. Skipped, and its title says why, without `dart`.
 */
const DART = onPath('dart')
const TIMEOUT = 3 * 60_000
const scratch: string[] = []
afterAll(() => scratch.forEach((dir) => rmSync(dir, { recursive: true, force: true })))

describe('platforms/dart', () => {
  it.skipIf(!DART)(
    DART
      ? 'passes dart analyze with no issues'
      : 'passes dart analyze with no issues (skipped: no `dart` on PATH)',
    async () => {
      const dir = mkdtempSync(join(tmpdir(), 'pm-dart-'))
      scratch.push(dir)
      cpSync(PACKAGE, dir, {
        recursive: true,
        filter: (path) => !path.includes('.dart_tool'),
      })
      writeFileSync(join(dir, 'lib/src/generated/probe.dart'), emitDart(probe))
      const result = await promisify(execFile)(DART!, ['analyze', '--fatal-infos', dir], {
        timeout: TIMEOUT,
        maxBuffer: 16 * 1024 * 1024,
      }).catch((error: { stdout?: string; stderr?: string; message: string }) => error)
      const failed = 'message' in result
      expect(
        failed ? `${result.stdout ?? ''}\n${result.stderr ?? ''}\n${result.message}` : '',
      ).toBe('')
    },
    TIMEOUT,
  )
})

