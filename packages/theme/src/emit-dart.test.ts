/** Each class in a Dart source, with its constructor's parameters in order. */
function dartClasses(source: string): Record<string, string[]> {
  const code = source.replace(/\/\/.*$/gm, '')
  return Object.fromEntries(
    [...code.matchAll(/class (\w+)[^{]*\{\s*const \1\(\{?([^)}]*)\}?\)/g)].map((match) => [
      match[1],
      [...(match[2] ?? '').matchAll(/(?:this|super)\.(\w+)/g)].map((name) => name[1]),
    ]),
  )
}

/** The absolute path of an executable on PATH, or null. */
function onPath(command: string): string | null {
  for (const dir of (process.env['PATH'] ?? '').split(delimiter)) {
    const candidate = join(dir, command)
    if (dir !== '' && existsSync(candidate)) return candidate
  }
  return null
}
