import { CHART_ROLES, COLOR_ROLES } from './roles'
import { composeTheme } from './systems'
import { SPRING_ROLES } from './tokens'

const quiet = resolveTheme(exampleQuietTheme)
const examples = EXAMPLE_THEMES.map(resolveTheme)

/** Every kind of value the emitter writes, exceptions included: the engine's shared probe. */
const probe = resolveTheme(exampleProbeTheme)
const themes = [...examples, probe]

const PACKAGE = resolve(process.cwd(), 'platforms/dart')
const TYPE_FILE = resolve(PACKAGE, 'lib/src/pm_theme.dart')
const GENERATED = resolve(PACKAGE, 'lib/src/generated')

/** The source with every call on one line, so a value can be found whatever the layout. */
const flatten = (source: string) =>
  source
    .replace(/([([])\s+/g, '$1')
    .replace(/,\s*([)\]])/g, '$1')
    .replace(/,\s+/g, ', ')

/** A Dart double: always with a decimal point. */
const double = (value: number) => {
  const text = fixedNumber(value)
  return text.includes('.') ? text : `${text}.0`
}

const rgba = ({ r, g, b, alpha }: TokenColor) => `PMRgba(${r}, ${g}, ${b}, ${double(alpha)})`

describe('emitDart', () => {
  const source = emitDart(quiet)
  const flat = flatten(source)

  it('is deterministic: the same theme gives the same bytes', () => {
    expect(emitDart(resolveTheme(exampleQuietTheme))).toBe(source)
    expect(emitDartFiles(examples)).toEqual(emitDartFiles(EXAMPLE_THEMES.map(resolveTheme)))
  })

  it('names its generator and pairing, and declares one const theme', () => {
    expect(source).toMatch(
      /^\/\/ Generated by `pnpm emit:native` from example-quiet\/example-violet\. Never hand-edited/,
    )
    expect(source).toContain("\nimport '../pm_theme.dart';\n")
    expect(source).toContain('\nconst PMTheme theme = PMTheme(\n')
    expect(source.trimEnd().endsWith(');')).toBe(true)
  })

  it('writes every colour and chart role in both modes, with the exact channels', () => {
    for (const theme of themes) {
      const doc = emitTokenDocument(theme, { platform: 'dart' })
      const text = flatten(emitDart(theme))
      const colors = text.slice(
        text.indexOf('colors: PMColors('),
        text.indexOf('chart: PMChartColors('),
      )
      const chart = text.slice(text.indexOf('chart: PMChartColors('), text.indexOf('gradients: '))
      for (const role of COLOR_ROLES) {
        const [light, dark] = [doc.mode.light.color[role], doc.mode.dark.color[role]]
        expect(colors, `${theme.name} ${role}`).toContain(
          `${nativeName(role)}: PMDynamicColor(light: ${rgba(light)}, dark: ${rgba(dark)})`,
        )
      }
      for (const role of CHART_ROLES) {
        const [light, dark] = [doc.mode.light.chart[role], doc.mode.dark.chart[role]]
        expect(chart, `${theme.name} ${role}`).toContain(
          `${nativeName(role, 'chart')}: PMDynamicColor(light: ${rgba(light)}, dark: ${rgba(dark)})`,
        )
      }
    }
  })

  it('writes all three densities and all four temperaments, whatever the axes select', () => {
    for (const density of DENSITIES) expect(flat).toContain(`${density}: PMDensity(space: [`)
    for (const temperament of MOTION_TEMPERAMENTS) {
      expect(flat).toContain(`${temperament}: PMMotion(duration: PMDurations(`)
    }
    for (const role of SPRING_ROLES) {
      expect(flat).toContain(`${nativeName(role)}: PMSpring(stiffness: `)
    }
    expect(flat).toContain(
      'base: PMSpring(stiffness: 300.0, damping: 30.0, mass: 1.0, dampingRatio: 0.866)',
    )
  })

  it("holds the hit target to Flutter's 48 floor, and keeps each control height the density's", () => {
    const heights = [
      ...flat.matchAll(
        /controlHeight: PMControlHeights\(sm: ([\d.]+), md: ([\d.]+), lg: ([\d.]+)\)/g,
      ),
    ]
    expect(heights.map((match) => match.slice(1).map(Number))).toEqual(
      DENSITIES.map((density) =>
        (['sm', 'md', 'lg'] as const).map((size) =>
          parseFloat(quiet.tokens.density[density].controlHeight[size]),
        ),
      ),
    )
    expect(PLATFORM_FLOORS.dart.hitTarget).toBe(48)
    expect(flat.match(/hitTarget: 48\.0, inset/g)).toHaveLength(DENSITIES.length)
  })

  it('lists the page texture as unsupported and gives it no value', () => {
    for (const theme of themes) {
      const text = emitDart(theme)
      expect(text).toContain("unsupported: ['texture.page']")
      expect(text).not.toMatch(/texture:|baseFrequency|strokeWidth/)
    }
  })

  it('resolves each declared exception as its kind', () => {
    const text = flatten(emitDart(probe))
    expect(text).toContain(
      "exceptions: [PMRadiusException(member: 'button', token: 'radius.control', ref: 'radius.sm', radius: 4.0), PMShadowException(member: 'card', token: 'shadow.resting', ref: 'shadow.overlay', shadow: PMShadow(layers: [",
    )
    expect(text).toMatch(
      /PMInsetException\(member: 'menu', token: 'inset\.list', ref: 'space\.4', inset: PMPerDensity\(compact: [\d.]+, standard: [\d.]+, comfortable: [\d.]+\)\)\]/,
    )
  })

  it('escapes what a Dart string would read as interpolation', () => {
    const named = resolveTheme(
      composeTheme(
        {
          ...exampleProbeSystem,
          fonts: { ...exampleProbeSystem.fonts, mono: { family: "Mono '$x' \\" } },
        },
        exampleVioletPalette,
      ),
    )
    expect(emitDart(named)).toContain("family: 'Mono \\'\\$x\\' \\\\'")
  })

  it('writes a control character as a \\u escape, which a one-line literal needs', () => {
    const named = resolveTheme(
      composeTheme(
        {
          ...exampleProbeSystem,
          fonts: { ...exampleProbeSystem.fonts, mono: { family: 'Mono\tCode\u007f' } },
        },
        exampleVioletPalette,
      ),
    )
    expect(emitDart(named)).toContain("family: 'Mono\\u0009Code\\u007f'")
  })
})

describe('emitDartFiles', () => {
  const files = emitDartFiles(examples)

  it('writes one library per pairing and a catalogue naming each one', () => {
    expect(Object.keys(files)).toEqual([
      'example_quiet_example_violet.dart',
      'example_stark_example_jade.dart',
      'example_quiet_example_ink.dart',
      'catalogue.dart',
    ])
    const catalogue = files['catalogue.dart']!
    expect(catalogue).toContain('abstract final class PMThemes {')
    expect(catalogue).toContain(
      "import 'example_quiet_example_violet.dart' as example_quiet_example_violet_lib;",
    )
    expect(catalogue).toContain(
      '  static const PMTheme exampleQuiet_exampleViolet = example_quiet_example_violet_lib.theme;',
    )
    for (const theme of examples) {
      expect(catalogue).toContain(`'${theme.system}/${theme.palette}' => `)
    }
    expect(catalogue).toContain('    _ => null,\n')
  })
})

describe('the committed generated files', () => {
  // A dotfile (Finder's `.DS_Store`) is local state, not a generated source.
  const generated = readdirSync(GENERATED)
    .filter((name) => !name.startsWith('.'))
    .map((name) => readFileSync(join(GENERATED, name), 'utf8'))

  it('carry the catalogue: one library per system, plus the catalogue', () => {
    const systems = readdirSync(resolve(process.cwd(), 'design/systems')).filter((file) =>
      file.endsWith('.json'),
    )
    expect(generated).toHaveLength(systems.length + 1)
  })

  it('contain no CSS: no var(), units, cubic-bezier() or colour functions', () => {
    for (const text of [...generated, emitDart(probe)]) {
      expect(text).not.toMatch(/var\(|cubic-bezier\(|linear-gradient\(|rgba?\(|\d(px|rem|em|ms)\b/)
    }
  })

  it('are exported by the package library', () => {
    const library = readFileSync(resolve(PACKAGE, 'lib/polymorph_tokens.dart'), 'utf8')
    expect(library).toContain("export 'src/generated/catalogue.dart';")
    expect(library).toContain("export 'src/pm_theme.dart';")
  })
})

describe('pm_theme.dart, the hand-written type file', () => {
  it('declares every class the emitter constructs, with its fields in order', () => {
    const trees = themes.map((theme) => nativeTheme(emitTokenDocument(theme, { platform: 'dart' })))
    const emitted = Object.fromEntries(nativeClasses(trees))
    const declared = dartClasses(readFileSync(TYPE_FILE, 'utf8'))
    // `PMException` is the sealed base the three exception classes extend.
    expect(declared['PMException']).toEqual(['member', 'token', 'ref'])
    delete declared['PMException']
    expect(declared).toEqual(emitted)
  })
})

describe('the quiet example', () => {
  it('matches its snapshot', () => {
    expect(emitDart(quiet)).toMatchSnapshot()
  })
})

