/**
 * `kotlinc` over the type file, every committed generated file and the
 * probe's output, warnings as errors. The freshness law (`native.test.ts`)
 * proves the files on disk are what the emitter writes; this proves Kotlin
 * accepts them, and the probe reaches the exception classes no catalogue
 * pairing declares. Skipped, and its title says why, without `kotlinc`. The
 * Gradle build (`platforms/android`) compiles the same sources and runs the
 * module's own tests; it needs the Kotlin plugin from the network once, so the
 * suite uses the compiler alone.
 */
const KOTLINC = onPath('kotlinc')
const TIMEOUT = 5 * 60_000
const scratch: string[] = []
afterAll(() => scratch.forEach((dir) => rmSync(dir, { recursive: true, force: true })))

describe('platforms/android', () => {
  it.skipIf(!KOTLINC)(
    KOTLINC ? 'compiles with kotlinc' : 'compiles with kotlinc (skipped: no `kotlinc` on PATH)',
    async () => {
      const dir = mkdtempSync(join(tmpdir(), 'pm-kotlin-'))
      scratch.push(dir)
      writeFileSync(join(dir, 'Probe.kt'), emitKotlin(probe))
      const result = await promisify(execFile)(
        KOTLINC!,
        [
          '-Werror',
          TYPES,
          resolve(MODULE, 'tokens/src/generated/kotlin'),
          dir,
          '-d',
          join(dir, 'out'),
        ],
        { timeout: TIMEOUT, maxBuffer: 16 * 1024 * 1024 },
      ).catch((error: { stdout?: string; stderr?: string; message: string }) => error)
      const failed = 'message' in result
      expect(
        failed ? `${result.stdout ?? ''}\n${result.stderr ?? ''}\n${result.message}` : '',
      ).toBe('')
    },
    TIMEOUT,
  )
})

