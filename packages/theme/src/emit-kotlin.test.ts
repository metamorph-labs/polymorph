import { execFile } from 'node:child_process'
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { delimiter, join, resolve } from 'node:path'
import { promisify } from 'node:util'

import { afterAll, describe, expect, it } from 'vitest'

import { DENSITIES, MOTION_TEMPERAMENTS } from './axes'
import { emitKotlin, emitKotlinFiles, KOTLIN_PACKAGE, kotlinNames } from './emit-kotlin'
import { emitTokenDocument, type TokenColor } from './emit-tokens'
import {
  EXAMPLE_THEMES,
  exampleProbeSystem,
  exampleProbeTheme,
  exampleQuietTheme,
  exampleVioletPalette,
} from './examples'
import { fixedNumber, nativeClasses, nativeName, nativeTheme } from './native-model'
import { PLATFORM_FLOORS } from './platforms'
import { resolveTheme } from './resolve-theme'
import { CHART_ROLES, COLOR_ROLES } from './roles'
import { composeTheme } from './systems'
import { SPRING_ROLES } from './tokens'

const quiet = resolveTheme(exampleQuietTheme)
const examples = EXAMPLE_THEMES.map(resolveTheme)

/** Every kind of value the emitter writes, exceptions included: the engine's shared probe. */
const probe = resolveTheme(exampleProbeTheme)
const themes = [...examples, probe]

const MODULE = resolve(process.cwd(), 'platforms/android')
const TYPES = resolve(MODULE, 'tokens/src/main/kotlin')
const TYPE_FILE = resolve(TYPES, 'dev/polymorph/tokens/PMTheme.kt')
const GENERATED = resolve(MODULE, 'tokens/src/generated/kotlin/dev/polymorph/tokens')

/** The source with every call on one line, so a value can be found whatever the layout. */
const flatten = (source: string) =>
  source
    .replace(/\(\s+/g, '(')
    .replace(/,\s*\)/g, ')')
    .replace(/,\s+/g, ', ')

const rgba = ({ r, g, b, alpha }: TokenColor) => `PMRgba(${r}, ${g}, ${b}, ${fixedNumber(alpha)}f)`

describe('emitKotlin', () => {
  const source = emitKotlin(quiet)
  const flat = flatten(source)

  it('is deterministic: the same theme gives the same bytes', () => {
    expect(emitKotlin(resolveTheme(exampleQuietTheme))).toBe(source)
    expect(emitKotlinFiles(examples)).toEqual(emitKotlinFiles(EXAMPLE_THEMES.map(resolveTheme)))
  })

  it('names its generator and pairing, and declares the package and the pairing object', () => {
    expect(source).toMatch(
      /^\/\/ Generated by `pnpm emit:native` from example-quiet\/example-violet\. Never hand-edited/,
    )
    expect(source).toContain(`\npackage ${KOTLIN_PACKAGE}\n`)
    expect(source).toContain(
      'internal object ExampleQuiet_ExampleViolet {\n    val theme: PMTheme = PMTheme(',
    )
  })

  it('writes every colour and chart role in both modes, with the exact channels', () => {
    for (const theme of themes) {
      const doc = emitTokenDocument(theme, { platform: 'android' })
      const text = flatten(emitKotlin(theme))
      const colors = text.slice(
        text.indexOf('colors = PMColors('),
        text.indexOf('chart = PMChartColors('),
      )
      const chart = text.slice(text.indexOf('chart = PMChartColors('), text.indexOf('gradients = '))
      for (const role of COLOR_ROLES) {
        const { light, dark } = {
          light: doc.mode.light.color[role],
          dark: doc.mode.dark.color[role],
        }
        expect(colors, `${theme.name} ${role}`).toContain(
          `${nativeName(role)} = PMDynamicColor(light = ${rgba(light)}, dark = ${rgba(dark)})`,
        )
      }
      for (const role of CHART_ROLES) {
        const { light, dark } = {
          light: doc.mode.light.chart[role],
          dark: doc.mode.dark.chart[role],
        }
        expect(chart, `${theme.name} ${role}`).toContain(
          `${nativeName(role, 'chart')} = PMDynamicColor(light = ${rgba(light)}, dark = ${rgba(dark)})`,
        )
      }
    }
  })

  it('writes all three densities and all four temperaments, whatever the axes select', () => {
    for (const density of DENSITIES)
      expect(flat).toContain(`${density} = PMDensity(space = listOf(`)
    for (const temperament of MOTION_TEMPERAMENTS) {
      expect(flat).toContain(`${temperament} = PMMotion(duration = PMDurations(`)
    }
    for (const role of SPRING_ROLES) {
      expect(flat).toContain(`${nativeName(role)} = PMSpring(stiffness = `)
    }
    expect(flat).toContain(
      'base = PMSpring(stiffness = 300f, damping = 30f, mass = 1f, dampingRatio = 0.866f)',
    )
  })

  it("holds the hit target to the 48dp floor, and keeps each control height the density's", () => {
    const heights = [
      ...flat.matchAll(
        /controlHeight = PMControlHeights\(sm = ([\d.]+)f, md = ([\d.]+)f, lg = ([\d.]+)f\)/g,
      ),
    ]
    expect(heights.map((match) => match.slice(1).map(Number))).toEqual(
      DENSITIES.map((density) =>
        (['sm', 'md', 'lg'] as const).map((size) =>
          parseFloat(quiet.tokens.density[density].controlHeight[size]),
        ),
      ),
    )
    expect(PLATFORM_FLOORS.android.hitTarget).toBe(48)
    expect(flat.match(/hitTarget = 48f, inset/g)).toHaveLength(DENSITIES.length)
  })

  it('lists the page texture as unsupported and gives it no value', () => {
    for (const theme of themes) {
      const text = emitKotlin(theme)
      expect(text).toContain('unsupported = listOf("texture.page")')
      expect(text).not.toMatch(/texture =|baseFrequency|strokeWidth/)
    }
  })

  it('resolves each declared exception as its kind', () => {
    const text = flatten(emitKotlin(probe))
    expect(text).toContain(
      'exceptions = listOf(PMRadiusException(member = "button", token = "radius.control", ref = "radius.sm", radius = 4f), PMShadowException(member = "card", token = "shadow.resting", ref = "shadow.overlay", shadow = PMShadow(layers = listOf(',
    )
    expect(text).toMatch(
      /PMInsetException\(member = "menu", token = "inset\.list", ref = "space\.4", inset = PMPerDensity\(compact = [\d.]+f, standard = [\d.]+f, comfortable = [\d.]+f\)\)\)/,
    )
  })

  it('escapes what a Kotlin string would read as a template', () => {
    const named = resolveTheme(
      composeTheme(
        {
          ...exampleProbeSystem,
          fonts: { ...exampleProbeSystem.fonts, mono: { family: 'Mono "$x" \\' } },
        },
        exampleVioletPalette,
      ),
    )
    expect(emitKotlin(named)).toContain('family = "Mono \\"\\$x\\" \\\\"')
  })

  it('writes a control character as a \\u escape, which a one-line literal needs', () => {
    const named = resolveTheme(
      composeTheme(
        {
          ...exampleProbeSystem,
          fonts: { ...exampleProbeSystem.fonts, mono: { family: 'Mono\tCode\u007f' } },
        },
        exampleVioletPalette,
      ),
    )
    expect(emitKotlin(named)).toContain('family = "Mono\\u0009Code\\u007f"')
  })
})

describe('emitKotlinFiles', () => {
  const files = emitKotlinFiles(examples)

  it('writes one file per pairing and a catalogue naming each one', () => {
    expect(Object.keys(files)).toEqual([
      'ExampleQuiet_ExampleViolet.kt',
      'ExampleStark_ExampleJade.kt',
      'ExampleQuiet_ExampleInk.kt',
      'Catalogue.kt',
    ])
    const catalogue = files['Catalogue.kt']!
    expect(catalogue).toContain('object PMThemes {')
    for (const theme of examples) {
      expect(catalogue).toContain(`"${theme.system}/${theme.palette}" -> `)
    }
    expect(catalogue).toContain(
      '    val exampleQuiet_exampleViolet: PMTheme get() = ExampleQuiet_ExampleViolet.theme',
    )
    expect(catalogue).toContain('        else -> null\n')
  })

  it('names the first pairing the default, or the one it is told', () => {
    expect(files['Catalogue.kt']).toContain(
      '    val default: PMTheme get() = exampleQuiet_exampleViolet\n',
    )
    const told = emitKotlinFiles(examples, {
      defaultPairing: { system: examples[1]!.system, palette: examples[1]!.palette },
    })
    expect(told['Catalogue.kt']).toContain(
      '    val default: PMTheme get() = exampleStark_exampleJade\n',
    )
    expect(() =>
      emitKotlinFiles(examples, { defaultPairing: { system: 'none', palette: 'none' } }),
    ).toThrow(/the default pairing none\/none is not among the pairings/)
    expect(emitKotlinFiles([])['Catalogue.kt']).not.toContain('val default')
  })
})

describe('the committed generated files', () => {
  // A dotfile (Finder's `.DS_Store`) is local state, not a generated source.
  const generated = readdirSync(GENERATED)
    .filter((name) => !name.startsWith('.'))
    .map((name) => readFileSync(join(GENERATED, name), 'utf8'))

  it('carry the catalogue: one file per system, plus the catalogue', () => {
    const systems = readdirSync(resolve(process.cwd(), 'design/systems')).filter((file) =>
      file.endsWith('.json'),
    )
    expect(generated).toHaveLength(systems.length + 1)
  })

  it('contain no CSS: no var(), units, cubic-bezier() or colour functions', () => {
    for (const text of [...generated, emitKotlin(probe)]) {
      expect(text).not.toMatch(/var\(|cubic-bezier\(|linear-gradient\(|rgba?\(|\d(px|rem|em|ms)\b/)
    }
  })
})

describe('PMTheme.kt, the hand-written type file', () => {
  it('declares every class the emitter constructs, with its properties in order', () => {
    const trees = themes.map((theme) =>
      kotlinNames(nativeTheme(emitTokenDocument(theme, { platform: 'android' }))),
    )
    const emitted = Object.fromEntries(nativeClasses(trees))
    expect(kotlinClasses(readFileSync(TYPE_FILE, 'utf8'))).toEqual(emitted)
  })

  it('names the icon sizes PMIconScale, as Swift does, so the member Icon can be PMIcon', () => {
    expect(emitKotlin(quiet)).toContain('PMIconScale(size = ')
    expect(emitKotlin(quiet)).not.toMatch(/\bPMIcon\(/)
  })
})

describe('the quiet example', () => {
  it('matches its snapshot', () => {
    expect(emitKotlin(quiet)).toMatchSnapshot()
  })
})

