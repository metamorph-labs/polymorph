/** Each `data class` in a Kotlin source, with its constructor properties in order. */
function kotlinClasses(source: string): Record<string, string[]> {
  const code = source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '')
  return Object.fromEntries(
    [...code.matchAll(/data class (\w+)\(([^)]*)\)/g)].map((match) => [
      match[1],
      [...(match[2] ?? '').matchAll(/val (\w+):/g)].map((name) => name[1]),
    ]),
  )
}

/** The absolute path of an executable on PATH, or null. */
function onPath(command: string): string | null {
  for (const dir of (process.env['PATH'] ?? '').split(delimiter)) {
    const candidate = join(dir, command)
    if (dir !== '' && existsSync(candidate)) return candidate
  }
  return null
}
